import test from 'node:test';
import assert from 'node:assert/strict';
import {npcNeedOpportunities,npcContactOpportunities,personalityHistory} from '../public/core/npc-life.mjs';
import {needForecast} from '../public/core/life-calendar.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
import {replay} from '../public/core/continuity.mjs';
import {characterStateView} from '../public/core/character-state.mjs';
const body='Recorded event.';
const sc=(id,time,events=[])=>({id,world_time:time,events,body});
const source=(scene_id,event_id,world_time)=>({scene_id,event_id,world_time});
const time='2000-01-01 08:00',later='2000-01-01 16:00';
const need=(actor,kind,status,src=source('a','need',time))=>({player_life_version:1,life_kind:'need',record_id:actor+kind,key:'need:'+actor+kind,actor,need:kind,status,source:src});
test('NPC needs use recorded baseline, exact chronological time and no guessed relief',()=>{
 const scenes=[sc('a',time),sc('b',later)],rows=[need('Lia','hunger','comfortable'),need('Tom','stress','urgent'),need('Ada','energy','unknown'),need('Harry','thirst','critical')];
 const before=JSON.stringify(rows);
 const result=npcNeedOpportunities(rows,scenes,later);
 const r=result.find(x=>x.row.actor==='Lia').info.need_review;
 assert.equal(r.estimated_status,'urgent');assert.equal(r.elapsed_minutes,480);
 assert.equal(r.estimated_status,needForecast(rows[0],scenes,later).estimated_status);
 assert.equal(result.find(x=>x.row.actor==='Tom').info.need_review.estimated_status,null);
 assert.ok(!result.some(x=>x.row.actor==='Ada'));
 assert.equal(JSON.stringify(rows),before);
 assert.deepEqual(npcNeedOpportunities(rows,scenes,later,{complete:false}),[]);
 const gap=[sc('a',time),sc('gap',null),sc('b',later)];
 assert.ok(!npcNeedOpportunities(rows,gap,later).some(x=>x.row.actor==='Lia'));
 const newNeed=need('Lia','hunger','comfortable',source('b','need',later));
 assert.equal(npcNeedOpportunities([newNeed],gap,'2000-01-02 00:00')[0].info.need_review.estimated_status,'urgent');
 const turn=prepareStoryTurn(scenes,{worldFacts:rows},[],{actors:['Harry'],limit:30});
 assert.ok(turn.npc_initiatives.initiatives.some(x=>x.actor==='Lia'&&x.kind==='need_review'));
 assert.ok(turn.npc_initiatives.initiatives.every(x=>x.actor!=='Harry'));
});
const episode=(id,actors)=>({id,type:'world',interaction_version:1,interaction_kind:'meeting',actors,description:'Met',evidence:body});
const relation=(id,a,b,patch)=>({id,type:'relationship',a,b,relationship_version:1,relationship_patch:patch,evidence:body});
test('social candidates honor directional boundaries, accepted episodes and pending invitations',()=>{
 const events=[episode('met',['Lia','Tom']),episode('blocked',['Lia','Ada']),relation('boundary','Ada','Lia',{boundary:'no_contact'}),relation('oneway','Tom','Harry',{trust:'trusted'}),episode('invalid',['Lia','Ghost'])];
 const scenes=[sc('a',time,events)];
 const projection={relationship_history:events.slice(0,4).map(e=>({source:source('a',e.id,time)})),relationships:[{a:'Ada',b:'Lia',relationship_fields:[{field:'boundary',value:'no_contact',source:source('a','boundary',time)}],source:source('a','boundary',time)},{a:'Tom',b:'Harry',relationship_fields:[{field:'trust',value:'trusted',source:source('a','oneway',time)}],source:source('a','oneway',time)}]};
 const contacts=npcContactOpportunities(scenes,projection,later);
 const pairs=contacts.map(x=>x.row.actor+'>'+x.row.counterparty).sort();
 assert.deepEqual(pairs,['Lia>Tom','Tom>Harry','Tom>Lia']);
 assert.equal(contacts.find(x=>x.row.actor==='Lia').info.contact.same_day,true);
 assert.deepEqual(contacts.find(x=>x.row.actor==='Lia').info.contact.own_fields,[]);
 const pending={...projection,worldFacts:[{player_life_version:1,life_kind:'invitation',actor:'Lia',recipient:'Tom',status:'sent'}]};
 assert.deepEqual(npcContactOpportunities(scenes,pending,later).map(x=>x.row.actor+'>'+x.row.counterparty),['Tom>Harry']);
 assert.deepEqual(npcContactOpportunities(scenes,projection,later,{complete:false}),[]);
});
test('possible new acquaintances remain bounded and are not established contacts',()=>{
 const scenes=[sc('a',time)];
 const basis=Array.from({length:12},(_,i)=>({actor:'NPC '+i,source:source('a','e'+i,time)}));
 const shared=[{kind:'group_opportunity',key:'g',title:'Group',basis}];
 const out=npcContactOpportunities(scenes,{},time,{shared});
 assert.equal(out.length,12);assert.ok(out.every(x=>x.kind==='social_encounter'&&x.row.actor!==x.row.counterparty&&x.info.contact.context==='group_opportunity'));
 const turn=prepareStoryTurn(scenes,{},[],{actors:['NPC 0']});
 assert.equal(turn.npc_initiatives.initiatives.length,0);
});
test('personality timeline uses explicit accepted before/after values, not inferred trends',()=>{
 const char=(id,patch)=>({id,type:'character',name:'Lia',state_patch:patch,evidence:body});
 const scenes=[sc('a',time,[char('start',{temperament:'Reserved',preference:'Tea'})]),sc('b',later,[char('change',{temperament:'More open'})]),sc('c','2000-01-02 08:00',[{...char('invalid',{temperament:'Invalid'}),evidence:'absent'}]),sc('d','2000-01-02 09:00',[char('same',{temperament:'More open'}),char('change2',{preference:null})])];
 const p=replay(scenes);
 const h=personalityHistory(scenes,p,['Lia']).get('Lia');
 assert.equal(h.total,2);
 assert.deepEqual(h.records.map(x=>[x.field,x.before,x.after]),[['preference','Tea',null],['temperament','Reserved','More open']]);
 assert.equal(h.records[1].source.scene_id,'b');
 assert.deepEqual(personalityHistory(scenes,p,['Lia'],{complete:false}).size,0);
 assert.equal(characterStateView(p,'Lia',{scenes}).personality_history.total,2);
 const turn=prepareStoryTurn(scenes,p,[],{actors:['Lia']});
 assert.equal(turn.actor_context.find(x=>x.actor==='Lia').personality_history.length,2);
});
