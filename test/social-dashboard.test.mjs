import test from 'node:test';
import assert from 'node:assert/strict';
import {createAncestryCache} from '../public/core/ancestry-cache.mjs';
import {createAncestryReader} from '../public/core/ancestry-reader.mjs';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {playerMenuOverview,menuSection,menuActionIntent} from '../public/core/game-menu.mjs';
import {npcInitiativeView} from '../public/core/npc-initiatives.mjs';
const evidence='Recorded event.';
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const chain=Array.from({length:1000},(_,i)=>({id:'s'+i,parent_scene_id:i?'s'+(i-1):null,events:[]}));
test('cache is scoped, bounded, immutable and expires without refreshing TTL',()=>{
 let now=0;const cache=createAncestryCache({maxEntries:2,ttlMs:10,now:()=>now});
 const result={scenes:chain,complete:true};
 assert.equal(cache.put('owner','world','branch','s999',50000,result),true);
 const hit=cache.get('owner','world','branch','s999',50000);
 hit.scenes[0].id='changed';
 assert.equal(cache.get('owner','world','branch','s999',50000).scenes[0].id,'s0');
 assert.equal(cache.get('other','world','branch','s999',50000),null);
 assert.equal(cache.get('owner','world','fork','s999',50000),null);
 assert.equal(cache.recent('owner','world','branch',50000).scenes.length,1000);
 assert.equal(cache.put('owner','world','branch','s999',50000,{...result,complete:false}),false);
 now=11;assert.equal(cache.get('owner','world','branch','s999',50000),null);
});
test('reuse complete prefix after verified newest page and reject divergent or capped ancestry',()=>{
 const latest={id:'new',parent_scene_id:'s999',events:[]};
 const reader=createAncestryReader('new',{pageSize:200});
 reader.accept([latest,...chain.slice(-199).reverse()]);
 assert.equal(reader.reusePrefix(chain),true);
 assert.deepEqual(reader.result().scenes,[...chain,latest]);
 const bad=createAncestryReader('other',{pageSize:1});bad.accept([{id:'other',parent_scene_id:'unknown'}]);assert.equal(bad.reusePrefix(chain),false);
 const capped=createAncestryReader('new',{pageSize:1,maxScenes:500});capped.accept([latest]);assert.equal(capped.reusePrefix(chain),false);
 const broken=createAncestryReader('new',{pageSize:1});broken.accept([latest]);assert.equal(broken.reusePrefix(chain.map((x,i)=>i===400?{...x,parent_scene_id:'wrong'}:x)),false);
});
const invite=life('invitation','tea',{actor:'Lia',recipient:'Harry',title:'Tea',place:'Cafe',invite_kind:'meeting',starts_at:'1994-08-01 14:00',ends_at:'1994-08-01 15:00',status:'sent'});
const appointment=life('appointment','tea',{actor:'Lia',participants:['Lia','Harry'],title:'Tea',place:'Cafe',starts_at:invite.starts_at,ends_at:invite.ends_at,status:'confirmed'});
const accepted={...invite,status:'accepted',appointment_id:'tea',outcome:'Harry agreed.'};
const health=life('health_episode','cold',{actor:'Harry',title:'Cold',health_kind:'illness',severity:'moderate',status:'observed',description:'Observed symptoms'});
test('invitations need explicit acceptance and matching appointment; menu does not answer',()=>{
 const h=[sc('s',[invite,health])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 const overview=playerMenuOverview(replay(h),'Harry','1994-08-01 09:00',{scenes:h});
 assert.equal(overview.social_dashboard.invitations.incoming.total,1);
 assert.ok(overview.dashboard.notifications.records.some(x=>x.kind==='invitation'));
 assert.equal(menuActionIntent({action:'respond_invitation',invitation_id:'tea',detail:'Agree'},overview).saved,false);
 assert.equal(menuSection(overview,'health').data.episodes.total,1);
 assert.equal(validateStateAppend(h,[accepted],evidence).ok,false);
 assert.equal(validateStateAppend(h,[appointment,accepted],evidence).ok,true);
 assert.equal(validateStateAppend(h,[appointment,{...accepted,place:'Other'}],evidence).ok,false);
 h.push(sc('accept',[appointment,accepted]));
 assert.equal(validateStateAppend(h,[{...accepted,status:'completed',outcome:'Met'}],evidence).ok,false);
 assert.equal(validateStateAppend(h,[{...appointment,status:'completed'},{...accepted,status:'completed',outcome:'Met'}],evidence).ok,true);
 assert.equal(validateStateAppend(h,[{...health,status:'resolved',description:'Recovered'}],evidence).ok,true);
 assert.equal(validateStateAppend([], [{...health,status:'resolved'}],evidence).ok,false);
});
test('social dashboard hides incoming private attitudes and exposes accepted shared episodes only',()=>{
 const own={id:'own',type:'relationship',a:'Harry',b:'Lia',stance:'friend',evidence};
 const hidden={id:'private',type:'relationship',a:'Lia',b:'Harry',stance:'secret',evidence};
 const shared={id:'met',type:'world',interaction_version:1,interaction_kind:'meeting',actors:['Harry','Lia'],description:'Met',evidence};
 const invalid={...shared,id:'invalid',evidence:'not present'};
 const h=[sc('s',[own,hidden,shared]),sc('bad',[invalid])];
 const p=replay(h),view=playerMenuOverview(p,'Harry',null,{scenes:h}).social_dashboard;
 assert.equal(view.contacts.total,1);assert.equal(view.contacts.records[0].own_attitude.stance,'friend');
 assert.equal(view.contacts.records[0].recent_interactions.length,1);assert.ok(!JSON.stringify(view).includes('secret'));
});
test('urgent initiatives precede optional ones and never answer for the player',()=>{
 const c=(actor,key,timing)=>({actors:[actor],key,title:key,kind:'intention',status:'active',timing});
 const v=npcInitiativeView([c('A','optional','unknown'),c('B','due1','reached_requires_story'),c('B','due2','reached_requires_story'),c('Harry','player','reached_requires_story')],{player:'Harry',settings:{agency:'normal',events:'low'}});
 assert.deepEqual(v.initiatives.map(x=>x.key),['due1','due2','optional']);
});
