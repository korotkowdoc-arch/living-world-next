import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {householdView} from '../public/core/households-careers.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
const evidence='Recorded event.',actor='Harry',host='Lia',currency='GBP';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const dyn=(dynamics_kind,record_id,extra)=>({id:dynamics_kind+'-'+record_id,type:'world',dynamics_version:1,dynamics_kind,record_id,key:'dynamics:'+dynamics_kind+':'+record_id,description:'Recorded',evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const estate=life('estate','home',{actor:host,title:'Home',place:'London',estate_kind:'house',status:'owned'});
const household=life('household','home',{actor:host,title:'Home',home_kind:'estate',home_id:'home',status:'active'});
const member=life('household_member','harry',{actor,host,household_id:'home',status:'invited'});
const cash={id:'cash',type:'money',actor,currency,operation:'reconcile',delta:0,balance:100,evidence};
const pay={id:'pay',type:'money',actor,counterparty:host,currency,operation:'transfer',delta:-20,evidence};
const contribution=life('household_contribution','rent',{actor,host,household_id:'home',title:'Rent share',amount:20,currency,transfer_event_id:'pay',status:'recorded'});
test('shared household requires invitation and access; payment is separate from title',()=>{
 const h=[sc('s',[estate,household,member,cash])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[pay,contribution]),false);
 assert.equal(valid(h,[{...member,status:'joined',outcome:'Agreed'}]),true);
 const o=playerMenuOverview(replay(h),actor);
 assert.equal(menuActionIntent({action:'respond_household',household_id:'home',member_id:'harry',detail:'Accept'},o).saved,false);
 assert.equal(householdView(replay(h),'Stranger').homes.total,0);
 h.push(sc('joined',[{...member,status:'joined',outcome:'Agreed'}]));
 assert.equal(valid(h,[contribution]),false);
 assert.equal(valid(h,[pay,contribution]),true);
 h.push(sc('paid',[pay,contribution]));
 assert.equal(replay(h).balances.find(x=>x.actor===actor).balance,80);
 assert.equal(menuSection(playerMenuOverview(replay(h),actor),'property').data.contributions.total,1);
 assert.equal(playerMenuOverview(replay(h),actor).property_systems.estates.total,0);
 const sale=life('estate_sale','sale',{actor:host,buyer:'Other',estate_id:'home',amount:0,currency,status:'offered'});
 h.push(sc('offer',[sale]),sc('accept',[{...sale,status:'accepted'}]),sc('sell',[{...sale,status:'settled',outcome:'Transferred'}]));
 assert.equal(householdView(replay(h),actor).homes.records[0].status,'access_unconfirmed');
 assert.equal(valid(h,[pay,{...contribution,record_id:'again',key:'player-life:household_contribution:again'}]),false);
 assert.equal(valid(h,[{...member,status:'left',outcome:'Moved away'}]),true);
});
const job=dyn('employment','job',{actor,counterparty:'Employer',title:'Clerk',status:'offered',amount:5,currency,pay_period:'hour'});
const req=life('job_requirement','job',{actor:'Employer',employment_id:'job',skills:[{name:'Accounting',level:'competent'}],status:'active'});
const skill={id:'skill',type:'world',growth_version:1,growth_kind:'skill',record_id:'accounting',key:'growth:skill:accounting',actor,name:'Accounting',status:'learning',description:'Learning',evidence};
test('job requires recorded own skills before accepting, no automatic dismissal after change',()=>{
 const h=[sc('offer',[job,req,skill])],p=replay(h);
 assert.deepEqual(p.validation_warnings,[]);
 assert.equal(valid(h,[{...job,status:'active'}]),false);
 assert.equal(householdView(p,actor).jobs.records[0].eligibility.status,'not_confirmed');
 assert.equal(householdView(p,'Employer').jobs.records[0].eligibility,null);
 assert.ok(prepareStoryTurn(h,p,[],{actors:[actor],limit:30}).candidates.some(x=>x.kind==='employment'&&x.checks.some(c=>c.kind==='qualification_unconfirmed')));
 h.push(sc('trained',[{...skill,status:'competent'}]));
 assert.equal(valid(h,[{...job,status:'active'}]),true);
 h.push(sc('hired',[{...job,status:'active'}]),sc('injured',[{...skill,status:'limited'}]));
 assert.equal(householdView(replay(h),actor).jobs.records[0].status,'active');
 assert.equal(valid(h,[{...job,status:'active'}]),true);
 assert.equal(valid(h,[{...req,record_id:'new',key:'player-life:job_requirement:new'}]),false);
});
test('care records require completed own health service; care does not cure',()=>{
 const episode=life('health_episode','cold',{actor,title:'Cold',health_kind:'illness',severity:'moderate',status:'observed',description:'Symptoms'});
 const service=life('venue_service','care',{actor:'Doctor',place:'Clinic',title:'Visit',category:'health',amount:0,currency,duration_minutes:20,status:'available'});
 const visit=life('service_visit','care',{actor,provider:'Doctor',service_id:'care',place:'Clinic',title:'Visit',amount:0,currency,status:'accepted'});
 const care=life('care_record','care',{actor,episode_id:'cold',visit_id:'care',description:'Consultation',status:'recorded'});
 const h=[sc('s',[episode,service,visit])];
 assert.equal(valid(h,[care]),false);
 assert.equal(valid(h,[{...visit,status:'completed',outcome:'Consulted'},care]),true);
 h.push(sc('care',[{...visit,status:'completed',outcome:'Consulted'},care]));
 const o=playerMenuOverview(replay(h),actor);
 assert.equal(menuSection(o,'health').data.care.total,1);
 assert.equal(o.social_dashboard.health.records[0].status,'observed');
 assert.equal(valid(h,[{...care,record_id:'dup',key:'player-life:care_record:dup'}]),false);
});
