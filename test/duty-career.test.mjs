import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {dutyCareerView} from '../public/core/duty-career.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
import {playerCalendar,planTimeAdvance} from '../public/core/life-calendar.mjs';
const evidence='Recorded event.',actor='Harry',host='Lia',currency='GBP';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const dyn=(dynamics_kind,record_id,extra)=>({id:dynamics_kind+'-'+record_id,type:'world',dynamics_version:1,dynamics_kind,record_id,key:'dynamics:'+dynamics_kind+':'+record_id,description:'Recorded',evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const estate=life('estate','home',{actor:host,title:'Home',place:'London',estate_kind:'house',status:'owned'});
const home=life('household','home',{actor:host,title:'Home',home_kind:'estate',home_id:'home',status:'active'});
const member=life('household_member','harry',{actor,host,household_id:'home',status:'invited'});
const duty=dyn('family_duty','clean',{actors:[host,actor],title:'Clean',family_kind:'household',starts_on:'1994-08-02',every_days:2,status:'active'});
const task=life('household_task','clean',{actor,host,household_id:'home',duty_id:'clean',title:'Clean',scheduled_on:'1994-08-02',status:'proposed'});
const event=dyn('family_event','clean',{actors:[host,actor],title:'Clean',family_kind:'household',duty_id:'clean',scheduled_on:'1994-08-02',status:'completed',outcome:'Cleaning completed'});
test('household task needs acceptance, accessible membership, unique slot and matching completed family occurrence',()=>{
 const h=[sc('root',[estate,home,member,duty])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[task]),false);
 h.push(sc('join',[{...member,status:'joined',outcome:'Agreed'}]));
 assert.equal(valid(h,[{...task,scheduled_on:'1994-08-03'}]),false);
 assert.equal(valid(h,[task]),true);h.push(sc('task',[task]));
 assert.equal(valid(h,[{...task,record_id:'dup',key:'player-life:household_task:dup'}]),false);
 const o=playerMenuOverview(replay(h),actor);
 assert.equal(menuActionIntent({action:'respond_household_task',household_task_id:'clean',detail:'Accept'},o).saved,false);
 assert.ok(o.dashboard.notifications.records.some(x=>x.kind==='household_task'));
 h.push(sc('accept',[{...task,status:'accepted',outcome:'Agreed'}]));
 const p=replay(h);
 assert.ok(playerCalendar(p,actor,'1994-08-01 09:00').entries.some(x=>x.kind==='household_task'));
 assert.equal(planTimeAdvance(h,p,actor,'1994-08-03 09:00',{pace:'fast'}).gate.kind,'household_task');
 const done={...task,status:'completed',family_event_id:'clean',outcome:'Completed'};
 assert.equal(valid(h,[done]),false);
 assert.equal(valid(h,[event]),false);
 assert.equal(valid(h,[event,done]),true);
 h.push(sc('done',[event,done],'1994-08-02 12:00'));
 assert.equal(dutyCareerView(replay(h),actor).tasks.records[0].status,'completed');
 assert.equal(valid(h,[{...task,record_id:'dup',key:'player-life:household_task:dup'}]),false);
});
const oldJob=dyn('employment','old',{actor,counterparty:'Employer',title:'Clerk',place:'Shop',amount:5,currency,pay_period:'hour',status:'active'});
const newJob={...oldJob,id:'new-job',record_id:'new',key:'dynamics:employment:new',title:'Manager',amount:10,status:'offered'};
const change=life('career_change','promotion',{actor,title:'Promotion',change_kind:'promotion',previous_job_id:'old',next_job_id:'new',status:'proposed'});
const shift=life('work_shift','old',{actor,employer:'Employer',employment_id:'old',title:'Shift',place:'Shop',starts_at:'1994-08-01 10:00',ends_at:'1994-08-01 11:00',pay_period:'hour',rate:5,currency,status:'scheduled'});
test('promotion preserves old wage, requires separate accepted job and closes unresolved shifts',()=>{
 const h=[sc('root',[oldJob,newJob,shift,change])];assert.deepEqual(replay(h).validation_warnings,[]);
 const end={...oldJob,status:'ended'},start={...newJob,status:'active'},done={...change,status:'completed',outcome:'Promoted'};
 assert.equal(valid(h,[end,start,done]),false);
 h.push(sc('work',[{...shift,status:'working'}]));
 h.push(sc('worked',[{...shift,status:'worked',worked_minutes:60,outcome:'Worked'}],'1994-08-01 11:00'));
 assert.equal(valid(h,[end,start,done]),true);
 h.push(sc('promoted',[end,start,done],'1994-08-01 11:00'));
 const o=playerMenuOverview(replay(h),actor);
 assert.equal(menuSection(o,'work').data.career_history.records[0].status,'completed');
 assert.equal(o.work_systems.shifts.records[0].earned,5);
 assert.equal(o.work_systems.shifts.records[0].settlement,'unpaid');
});
const con={id:'con',type:'world',consequence_version:1,consequence_kind:'social',record_id:'con',key:'consequence:con',actor,responsible:host,status:'active',description:'Disagreement',evidence};
const response=life('consequence_response','repair',{actor:host,title:'Discuss',consequence_id:'con',due_at:'1994-08-01 09:00',action_description:'Talk',status:'planned'});
test('NPC response is independent, not a resolution or hidden player notification',()=>{
 const h=[sc('root',[con,response])],p=replay(h);assert.deepEqual(p.validation_warnings,[]);
 assert.equal(dutyCareerView(p,actor).responses.total,0);
 assert.equal(dutyCareerView(p,host).responses.total,1);
 assert.equal(dutyCareerView(p,'Stranger').consequences.total,0);
 const t=prepareStoryTurn(h,p,[],{actors:[actor],limit:30});
 assert.ok(t.npc_initiatives.initiatives.some(x=>x.kind==='consequence_response'&&x.actor===host));
 assert.equal(valid(h,[{...response,status:'performed',result:'resolved',outcome:'Talked'}]),false);
 assert.equal(valid(h,[{...response,status:'performed',result:'attempted',outcome:'Talked'}]),true);
 const resolved={...con,status:'resolved',outcome:'Resolved'};
 assert.equal(valid(h,[resolved,{...response,status:'performed',result:'resolved',outcome:'Talked'}]),true);
});
