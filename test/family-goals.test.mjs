import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend,replayWithCheckpoint} from '../public/core/continuity.mjs';
import {familyGoalView,fictionalAge} from '../public/core/family-goals.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
import {playerCalendar,planTimeAdvance} from '../public/core/life-calendar.mjs';
const evidence='Recorded event.',actor='Harry',other='Lia',child='Alex';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const dyn=(dynamics_kind,record_id,extra)=>({id:dynamics_kind+'-'+record_id,type:'world',dynamics_version:1,dynamics_kind,record_id,key:'dynamics:'+dynamics_kind+':'+record_id,description:'Recorded',evidence,...extra});
const sc=(id,events=[],world_time='2000-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e,worldTime='2000-08-01 09:00')=>validateStateAppend(h,e,evidence,{worldTime}).ok;
const birthEvent=dyn('family_event','birth',{actors:[actor,other,child],title:'Birth',family_kind:'birth',status:'completed',outcome:'Born'});
const bond=dyn('bond','parent',{actor,counterparty:child,bond_type:'parenthood',status:'active'});
const birth=life('child_birth','child',{actor:child,parent:actor,born_on:'2000-08-01',family_event_id:'birth',status:'recorded'});
test('birth and milestones require actual dated scene and parenthood; age is derived without automatic development',()=>{
 assert.equal(valid([], [birthEvent,birth]),false);
 assert.equal(valid([], [bond,birthEvent,birth],null),false);
 assert.equal(valid([], [bond,birthEvent,birth],'2000-08-02'),false);
 assert.equal(valid([], [bond,birthEvent,birth]),true);
 const h=[sc('birth',[bond,birthEvent,birth])],p=replay(h);
 assert.deepEqual(p.validation_warnings,[]);
 assert.equal(familyGoalView(p,actor,'2001-07-31').children.records[0].age_years,0);
 assert.equal(familyGoalView(p,actor,'2001-08-01').children.records[0].age_years,1);
 assert.equal(familyGoalView(p,actor,'1999-08-01').children.records[0].age_years,null);
 assert.equal(familyGoalView(p,'Stranger','2001-08-01').children.total,0);
 assert.equal(fictionalAge('2000-02-29','2001-02-28'),0);
 assert.equal(fictionalAge('2000-02-29','2001-03-01'),1);
 assert.equal(valid(h,[{...birth,record_id:'dup',key:'player-life:child_birth:dup'}]),false);
 const event=dyn('family_event','school',{actors:[actor,child],title:'First school day',family_kind:'education',status:'completed',outcome:'Attended'});
 const milestone=life('child_milestone','school',{actor,child_id:'child',family_event_id:'school',occurred_on:'2006-09-01',title:'First school day',category:'education',description:'Attended school',status:'recorded'});
 assert.equal(valid(h,[event,milestone],'2006-09-02'),false);
 assert.equal(valid(h,[event,{...milestone,actor:other}],'2006-09-01'),false);
 assert.equal(valid(h,[milestone],'2006-09-01'),false);
 assert.equal(valid(h,[event,milestone],'2006-09-01'),true);
 const full=[...h,sc('school',[event,milestone],'2006-09-01')];
 const cp=replayWithCheckpoint(h,{evidencePrevalidated:true}).checkpoint;
 assert.deepEqual(replayWithCheckpoint(full,{evidencePrevalidated:true,checkpoint:cp}).projection,replay(full,[],{evidencePrevalidated:true}));
 const o=playerMenuOverview(replay(full),actor,{clock:'2006-09-01'});
 assert.equal(menuSection(o,'relationships').data.children.records[0].milestones.total,1);
 assert.equal(menuActionIntent({action:'record_child_milestone',child_id:'child',detail:'Help with studies'},o).saved,false);
});
const goal=life('shared_goal','home',{actor,title:'Build home',description:'Shared project',due_at:'2000-08-02 10:00',steps:[{id:'plan',title:'Plan'},{id:'prepare',title:'Prepare'}],status:'proposed'});
const invite=life('shared_goal_member','lia',{actor:other,organizer:actor,goal_id:'home',status:'invited'});
const activity=(id,who)=>({id:'activity-'+id,type:'world',activity_version:1,activity_kind:'activity',record_id:id,key:'activity:activity:'+id,name:'Work',description:'Worked',actors:[who],status:'completed',outcome:'Done',evidence});
const step=(id,who,which,act)=>life('shared_goal_step',id,{actor:who,goal_id:'home',step_id:which,completion_kind:'activity',completion_id:act,status:'completed',outcome:'Done'});
test('shared goals require voluntary membership, actual distinct steps and explicit closure',()=>{
 const h=[sc('proposal',[goal,invite])],p=replay(h);
 assert.deepEqual(p.validation_warnings,[]);
 assert.equal(valid(h,[{...goal,status:'active'}]),false);
 assert.equal(familyGoalView(p,'Stranger').goals.total,0);
 const o=playerMenuOverview(p,other);
 assert.equal(o.family_goals.goals.records[0].steps[0].completed,null);
 assert.equal(menuActionIntent({action:'respond_shared_goal',goal_id:'home',membership_id:'lia',detail:'Agree'},o).saved,false);
 assert.ok(prepareStoryTurn(h,p,[],{actors:[actor],limit:30}).npc_initiatives.initiatives.some(x=>x.kind==='shared_goal_invitation'&&x.actor===other));
 h.push(sc('accept',[{...invite,status:'accepted',outcome:'Agreed'},{...goal,status:'active'}]));
 const active=replay(h);
 assert.ok(playerCalendar(active,other,'2000-08-01 09:00').entries.some(x=>x.kind==='shared_goal'));
 assert.equal(planTimeAdvance(h,active,actor,'2000-08-03 09:00',{pace:'fast'}).gate.kind,'shared_goal');
 assert.ok(prepareStoryTurn(h,active,[],{actors:[actor],limit:30}).npc_initiatives.initiatives.some(x=>x.kind==='shared_goal'&&x.actor===other));
 const s1=step('first',other,'plan','a'),s2=step('second',actor,'prepare','b');
 const done={...goal,status:'completed',outcome:'Finished'};
 assert.equal(valid(h,[done]),false);
 assert.equal(valid(h,[s1]),false);
 assert.equal(valid(h,[activity('a',actor),s1]),false);
 assert.equal(valid(h,[activity('a',other),s1]),true);
 h.push(sc('first',[activity('a',other),s1]));
 assert.equal(valid(h,[activity('a',other),step('dup',other,'prepare','a')]),false);
 assert.equal(valid(h,[activity('b',actor),s2,done]),true);
 h.push(sc('finish',[activity('b',actor),s2,done]));
 const end=familyGoalView(replay(h),actor).goals.records[0];
 assert.equal(end.status,'completed');assert.equal(end.steps.filter(x=>x.completed).length,2);
 assert.equal(valid(h,[{...invite,status:'left',outcome:'Left'}]),false);
});
