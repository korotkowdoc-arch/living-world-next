import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend,validateScene} from '../public/core/continuity.mjs';
import {workView,shiftWage} from '../public/core/work-systems.mjs';
import {playerMenuOverview,menuActionIntent} from '../public/core/game-menu.mjs';
import {planTimeAdvance,playerCalendar} from '../public/core/life-calendar.mjs';
const actor='Harry',employer='Cafe',currency='GBP',evidence='Recorded event.';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const dyn=(dynamics_kind,record_id,extra)=>({id:dynamics_kind+'-'+record_id,type:'world',dynamics_version:1,dynamics_kind,record_id,key:'dynamics:'+dynamics_kind+':'+record_id,description:'Recorded',evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,body:evidence,events,world_time});
const valid=(s,e)=>validateStateAppend(s,e,evidence).ok;
const job=dyn('employment','job',{actor,counterparty:employer,title:'Cafe assistant',place:'Cafe',status:'active',amount:12,currency,pay_period:'hour'});
const shift=life('work_shift','shift',{actor,employer,employment_id:'job',title:'Morning shift',place:'Cafe',starts_at:'1994-08-01 10:00',ends_at:'1994-08-01 14:00',pay_period:'hour',rate:12,currency,status:'scheduled'});
const worked={...shift,status:'worked',worked_minutes:210,outcome:'Served customers.'};
const cash={id:'cash',type:'money',actor:employer,currency,operation:'reconcile',balance:100,delta:0,evidence};
const wage=life('wage','wage',{actor,employer,shift_id:'shift',status:'paid',amount:42,currency,transfer_event_id:'salary'});
const salary={id:'salary',type:'money',actor:employer,counterparty:actor,currency,operation:'transfer',delta:-42,evidence};
test('shift is tied to active employment and wages are paid exactly once',()=>{
 const history=[sc('job',[job,cash,shift])];
 assert.deepEqual(replay(history).validation_warnings,[]);
 assert.equal(valid(history,[{...shift,status:'worked',worked_minutes:210,outcome:'Done'}]),false);
 assert.equal(valid([], [shift]),false);
 assert.equal(valid([sc('job',[job])],[{...shift,rate:13}]),false);
 assert.equal(valid(history,[{...shift,status:'working'}]),true);
 history.push(sc('start',[{...shift,status:'working'}],'1994-08-01 10:00'));
 assert.equal(valid(history,[{...worked,worked_minutes:241}]),false);
 assert.equal(valid(history,[{...worked,ends_at:'1994-08-01 15:00'}]),false);
 assert.equal(valid(history,[worked]),true);
 history.push(sc('end',[worked],'1994-08-01 14:00'));
 assert.equal(shiftWage(worked),42);
 assert.equal(shiftWage({...worked,rate:1,worked_minutes:1}),null);
 assert.equal(workView(replay(history),actor).shifts.records[0].settlement,'unpaid');
 assert.equal(valid(history,[wage,salary]),false);
 assert.equal(valid(history,[salary,{...wage,amount:43}]),false);
 assert.equal(valid(history,[salary,wage]),true);
 history.push(sc('pay',[salary,wage],'1994-08-01 14:00'));
 assert.equal(workView(replay(history),actor).shifts.records[0].settlement,'paid');
 assert.equal(valid(history,[salary,wage]),false);
});
const service=life('venue_service','meal',{actor:employer,place:'Cafe',title:'Meal',category:'food',amount:10,currency,duration_minutes:30,status:'available'});
const lines=[{product_id:'bread',unit:'piece',quantity:-2}];
const recipe=life('service_recipe','recipe',{actor:employer,service_id:'meal',status:'active',stock_lines:lines});
const visit=life('service_visit','lunch',{actor,service_id:'meal',provider:employer,place:'Cafe',title:'Meal',amount:10,currency,status:'accepted',recipe_id:'recipe'});
const stock=dyn('stock_operation','count',{actor:employer,status:'recorded',stock_action:'count',stock_lines:[{product_id:'bread',unit:'piece',quantity:3}]});
const consume=dyn('stock_operation','use',{actor:employer,status:'recorded',stock_action:'consume',stock_lines:lines});
const payment={id:'meal-pay',type:'money',actor,counterparty:employer,currency,operation:'transfer',delta:-10,evidence};
const complete={...visit,status:'completed',outcome:'Ate meal.',transfer_event_id:'meal-pay',stock_event_id:consume.id};
test('service acceptance pins recipe; completion needs correct stock consumption and payment',()=>{
 const h=[sc('shop',[service,recipe,stock])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[{...visit,recipe_id:null}]),false);
 assert.equal(valid(h,[visit]),true);
 h.push(sc('accepted',[visit,{...cash,actor}]));
 assert.equal(valid(h,[payment,complete]),false);
 assert.equal(valid(h,[payment,{...consume,stock_lines:[{...lines[0],quantity:-1}]},complete]),false);
 assert.equal(valid(h,[payment,consume,complete]),true);
 const p=replay([...h,sc('served',[payment,consume,complete])]);
 assert.equal(p.stock.find(x=>x.product_id==='bread').quantity,1);
 assert.equal(workView(p,employer).recipes.records[0].stock_lines[0].sufficient,false);
 assert.equal(workView(p,actor).recipes.total,0);
 assert.equal(valid(h,[{...recipe,stock_lines:[{...lines[0],quantity:-1}]}]),false);
 assert.equal(validateScene({body:evidence,events:[payment,consume,complete,{...complete,id:'other',record_id:'other',key:'player-life:service_visit:other',amount:0,transfer_event_id:null}]}).ok,false);
});
test('known transit and work calendar are personal and time-aware',()=>{
 const notice=life('transit_notice','train',{actor,provider:'Rail',title:'Train',from:'Station',to:'London',mode:'rail',departs_at:'1994-08-01 10:00',arrives_at:'1994-08-01 11:00',amount:5,currency,status:'scheduled'});
 const h=[sc('start',[job,shift,notice])],p=replay(h);
 assert.deepEqual(p.validation_warnings,[]);
 assert.equal(workView(p,'Other','1994-08-01 09:00').transport.total,0);
 assert.equal(workView(p,actor,'1994-08-01 11:00').transport.records[0].timing,'past');
 assert.equal(menuActionIntent({action:'choose_transport',transit_id:'train',detail:'Take train'},playerMenuOverview(p,actor,'1994-08-01 09:00')).saved,false);
 assert.throws(()=>menuActionIntent({action:'choose_transport',transit_id:'train',detail:'Take train'},playerMenuOverview(p,actor,'1994-08-01 11:00')));
 assert.equal(planTimeAdvance(h,p,actor,'1994-08-02 09:00').gate.kind,'work_shift');
 assert.equal(playerCalendar(p,actor,'1994-08-01 09:00').entries.some(x=>x.kind==='work_shift'),true);
});
