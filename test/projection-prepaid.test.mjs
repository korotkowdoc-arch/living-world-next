import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,replayWithCheckpoint,validateStateAppend} from '../public/core/continuity.mjs';
import {createProjectionCache} from '../public/core/projection-cache.mjs';
import {reviewSceneDraft} from '../public/core/scene-draft.mjs';
import {playerMenuOverview,menuSection,menuActionIntent} from '../public/core/game-menu.mjs';
const evidence='Recorded event.',actor='Harry',currency='GBP';
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const cash={id:'cash',type:'money',actor,currency,operation:'reconcile',delta:0,balance:100,evidence};
const pending={id:'choice',type:'world',dynamics_version:1,dynamics_kind:'player_choice',record_id:'choice',key:'dynamics:player_choice:choice',actor,status:'pending',description:'Decision',question:'What now?',options:[{id:'yes',text:'Go'},{id:'no',text:'Stay'}],evidence};
const answer={id:'answer',type:'world',dynamics_version:1,dynamics_kind:'player_choice',record_id:'choice',key:'dynamics:player_choice:choice',actor,status:'answered',description:'Decision',selected_option:'yes',action_text:'Go',evidence};
const start={id:'plan',type:'plan',actor,plan_id:'plan',action:'start',goal:'Learn',evidence};
test('resumed projection equals full replay across thousands of scenes, budget and pending choice',()=>{
 const prefix=[sc('root',[cash,start]),...Array.from({length:3000},(_,i)=>sc('s'+i,[{id:'p',type:'plan',actor,plan_id:'plan',action:'advance',evidence}])),sc('payment',[{id:'pay',type:'money',actor,currency,delta:-10,evidence}]),sc('pending',[pending])];
 const cp=replayWithCheckpoint(prefix,{evidencePrevalidated:true}),saved=JSON.stringify(cp.checkpoint);
 assert.equal(cp.replayed_scenes,prefix.length);
 const tail=sc('answer',[answer,{id:'pay2',type:'money',actor,currency,delta:-5,evidence}]);
 const history=[...prefix,tail];
 const resumed=replayWithCheckpoint(history,{checkpoint:JSON.parse(saved),evidencePrevalidated:true});
 assert.equal(resumed.replayed_scenes,1);assert.equal(resumed.reused_scenes,prefix.length);
 const full=replay(history,[],{evidencePrevalidated:true});
 // In-memory checkpoint preserves optional undefined fields. The Worker cache
 // serializes JSON, so its contract is exact JSON equality (undefined is absent).
 assert.deepEqual(replayWithCheckpoint(history,{checkpoint:cp.checkpoint,evidencePrevalidated:true}).projection,full);
 assert.deepEqual(JSON.parse(JSON.stringify(resumed.projection)),JSON.parse(JSON.stringify(full)));
 assert.equal(resumed.projection.budget_flows[0].expense,15);
 assert.equal(JSON.stringify(cp.checkpoint),saved);
 const refused=replayWithCheckpoint([...prefix,sc('wrong',[])],{checkpoint:cp.checkpoint,evidencePrevalidated:true});
 assert.equal(refused.projection.validation_warnings.at(-1).scene_id,'wrong');
 const divergent=[...prefix.slice(0,-1),sc('other',[])];
 assert.equal(replayWithCheckpoint(divergent,{checkpoint:cp.checkpoint,evidencePrevalidated:true}).reused_scenes,0);
 assert.equal(replayWithCheckpoint(history,{checkpoint:cp.checkpoint,evidencePrevalidated:false}).reused_scenes,0);
 const preview=reviewSceneDraft({scenes:prefix,complete:true,projection:cp.projection,checkpoint:cp.checkpoint},{body:evidence,events:tail.events,world_time:tail.world_time});
 assert.equal(preview.ok,true);assert.equal(preview.events_accepted,2);assert.equal(preview.saved,false);
});
test('projection cache is scoped to authenticated owner/branch and never caches incomplete history',()=>{
 let now=0;const cache=createProjectionCache({maxEntries:2,ttlMs:10,now:()=>now});
 const base={complete:true,scenes:[sc('a',[cash])]};
 assert.equal(cache.project('owner','world','branch',base).replayed_scenes,1);
 const exact=cache.project('owner','world','branch',base);assert.equal(exact.replayed_scenes,0);
 exact.projection.balances[0].balance=0;
 assert.equal(cache.project('owner','world','branch',base).projection.balances[0].balance,100);
 const next={complete:true,scenes:[...base.scenes,sc('b',[])]};
 assert.equal(cache.project('owner','world','branch',next).replayed_scenes,1);
 assert.equal(cache.project('other','world','branch',next).reused_scenes,0);
 assert.equal(cache.project('owner','world','fork',next).reused_scenes,0);
 assert.equal(cache.project('owner','world','fork',{...next,complete:false}).checkpoint,null);
 now=11;assert.equal(cache.stats().entries,0);
});
const provider='Rail';
const service=life('venue_service','train',{actor:provider,title:'Train',place:'Station',category:'transport',amount:10,currency,duration_minutes:60,status:'available'});
const notice=life('transit_notice','train',{actor,provider,title:'Train',from:'Station',to:'London',mode:'rail',departs_at:'1994-08-01 10:00',arrives_at:'1994-08-01 11:00',amount:10,currency,status:'scheduled'});
const slot=life('capacity_slot','seat',{actor:provider,service_id:'train',resource:'Seat',starts_at:notice.departs_at,ends_at:notice.arrives_at,capacity:1,status:'open'});
const visit=life('service_visit','train',{actor,provider,service_id:'train',title:'Train',place:'Station',amount:10,currency,status:'accepted'});
const reserve=life('reservation','seat',{actor,slot_id:'seat',visit_id:'train',units:1,status:'reserved'});
const ticket=life('transport_ticket','ticket',{actor,notice_id:'train',reservation_id:'seat',visit_id:'train',title:'Train',from:notice.from,to:notice.to,departs_at:notice.departs_at,arrives_at:notice.arrives_at,status:'reserved'});
const receipt=life('ticket_payment','paid',{actor,provider,ticket_id:'ticket',reservation_id:'seat',visit_id:'train',amount:10,currency,transfer_event_id:'payment',status:'paid'});
const payment={id:'payment',type:'money',actor,counterparty:provider,currency,delta:-10,operation:'transfer',evidence};
const h=[sc('root',[cash,service,notice,slot,visit,reserve,ticket])];
const valid=(history,events)=>validateStateAppend(history,events,evidence).ok;
test('paid ticket settles once without second charge, and refund is exact atomic cancellation',()=>{
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[receipt,payment]),false);
 assert.equal(valid(h,[{...payment,delta:-9},receipt]),false);
 assert.equal(valid(h,[payment,receipt]),true);
 const paid=[...h,sc('paid',[payment,receipt])],p=replay(paid),overview=playerMenuOverview(p,actor);
 assert.equal(p.balances.find(x=>x.actor===actor).balance,90);
 assert.equal(menuSection(overview,'places').data.payments.records[0].status,'paid');
 assert.equal(menuActionIntent({action:'refund_ticket',ticket_id:'ticket',detail:'Cancel'},overview).saved,false);
 assert.equal(valid(paid,[payment,{...receipt,record_id:'dup',key:'player-life:ticket_payment:dup'}]),false);
 const done={...visit,status:'completed',outcome:'Arrived',prepayment_id:'paid'};
 assert.equal(valid(paid,[payment,{...visit,status:'completed',outcome:'Arrived',transfer_event_id:'payment'}]),false);
 assert.equal(valid(h,[done]),false);
 const used=[done,{...reserve,status:'used'},{...ticket,status:'used'}];
 assert.equal(valid(paid,used),true);
 const complete=replay([...paid,sc('travel',used)]);
 assert.equal(complete.balances.find(x=>x.actor===actor).balance,90);
 assert.equal(playerMenuOverview(complete,actor).ticket_payments.records[0].status,'consumed');
 const refund={id:'refund',type:'money',actor:provider,counterparty:actor,currency,delta:-10,operation:'transfer',evidence};
 const refunded={...receipt,status:'refunded',transfer_event_id:'refund'};
 const cancel=[{...visit,status:'cancelled'},{...reserve,status:'cancelled'},{...ticket,status:'cancelled'}];
 assert.equal(valid(paid,cancel),false);assert.equal(valid(paid,[refund,refunded]),false);
 assert.equal(valid(paid,[refund,refunded,...cancel]),true);
 const final=replay([...paid,sc('refund',[refund,refunded,...cancel])]);
 assert.equal(final.balances.find(x=>x.actor===actor).balance,100);
 assert.equal(playerMenuOverview(final,actor).ticket_payments.records[0].status,'refunded');
 assert.equal(valid([...paid,sc('travel',used)],[refund,refunded,...cancel]),false);
});
