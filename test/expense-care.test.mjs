import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {expenseCareView} from '../public/core/expense-care.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
import {playerCalendar,planTimeAdvance} from '../public/core/life-calendar.mjs';
const evidence='Recorded event.',actor='Harry',host='Lia',currency='GBP';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const estate=life('estate','home',{actor:host,title:'Home',place:'London',estate_kind:'house',status:'owned'});
const home=life('household','home',{actor:host,title:'Home',home_kind:'estate',home_id:'home',status:'active'});
const member=(a,id)=>life('household_member',id,{actor:a,host,household_id:'home',status:'invited'});
const m=member(actor,'harry'),n=member('Other','other');
const cash=a=>({id:'cash-'+a,type:'money',actor:a,currency,operation:'reconcile',delta:0,balance:100,evidence});
const bill={id:'bill',type:'money',actor:host,counterparty:'Store',currency,operation:'transfer',delta:-60,evidence};
const expense=life('household_expense','bill',{actor:host,household_id:'home',title:'Groceries',provider:'Store',category:'food',amount:60,currency,source_kind:'direct',transfer_event_id:'bill',status:'recorded'});
const share=life('expense_share','share',{actor,host,household_id:'home',expense_id:'bill',title:'Groceries share',amount:25,currency,due_at:'1994-08-02 10:00',status:'proposed'});
const payment={id:'pay',type:'money',actor,counterparty:host,currency,operation:'transfer',delta:-25,evidence};
const contribution=life('household_contribution','part',{actor,host,household_id:'home',title:'Share',amount:25,currency,transfer_event_id:'pay',status:'recorded'});
test('expense shares cannot exceed actual paid expense or duplicate the ledger, and keep member privacy',()=>{
 const h=[sc('root',[estate,home,m,n,cash(actor),cash(host)])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 h.push(sc('join',[{...m,status:'joined',outcome:'Joined'},{...n,status:'joined',outcome:'Joined'}]));
 assert.equal(valid(h,[expense]),false);
 assert.equal(valid(h,[bill,expense]),true);h.push(sc('paid',[bill,expense]));
 assert.equal(valid(h,[{...share,status:'accepted',outcome:'Agreed'}]),false);
 h.push(sc('share',[share]));
 const other={...share,id:'other-share',record_id:'other',key:'player-life:expense_share:other',actor:'Other',amount:36};
 assert.equal(valid(h,[other]),false);assert.equal(valid(h,[{...other,amount:35}]),true);
 h.push(sc('other',[{...other,amount:35}]));
 assert.equal(expenseCareView(replay(h),actor).shares.total,1);
 assert.equal(expenseCareView(replay(h),'Stranger').expenses.total,0);
 assert.equal(menuActionIntent({action:'respond_expense_share',share_id:'share',detail:'Agree'},playerMenuOverview(replay(h),actor)).saved,false);
 h.push(sc('accept',[{...share,status:'accepted',outcome:'Agreed'}]));
 const p=replay(h);
 assert.ok(playerCalendar(p,actor,'1994-08-01 09:00').entries.some(x=>x.kind==='expense_share'));
 assert.equal(planTimeAdvance(h,p,actor,'1994-08-03 09:00',{pace:'fast'}).gate.kind,'expense_share');
 const paid={...share,status:'paid',contribution_id:'part',outcome:'Paid'};
 assert.equal(valid(h,[paid]),false);
 assert.equal(valid(h,[payment,contribution,paid]),true);
 h.push(sc('reimburse',[payment,contribution,paid]));
 const end=replay(h);
 assert.equal(end.balances.find(x=>x.actor===host).balance,65);
 assert.equal(end.balances.find(x=>x.actor===actor).balance,75);
 assert.equal(expenseCareView(end,host).expenses.records[0].host_net_paid,35);
 assert.equal(menuSection(playerMenuOverview(end,actor),'finances').data.expense_shares.records[0].status,'paid');
 assert.equal(valid(h,[payment,contribution,paid]),false);
});
test('completed service can become an expense without a second payment',()=>{
 const service=life('venue_service','food',{actor:'Store',place:'Store',title:'Food',category:'food',amount:60,currency,duration_minutes:20,status:'available'});
 const visit=life('service_visit','food',{actor:host,provider:'Store',service_id:'food',place:'Store',title:'Food',amount:60,currency,status:'accepted'});
 const h=[sc('root',[estate,home,cash(host),service,visit])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 const receipt={...expense,source_kind:'service',visit_id:'food',transfer_event_id:null};
 assert.equal(valid(h,[receipt]),false);
 h.push(sc('visit',[bill,{...visit,status:'completed',transfer_event_id:'bill',outcome:'Purchased'}]));
 assert.equal(valid(h,[receipt]),true);h.push(sc('expense',[receipt]));
 assert.equal(replay(h).balances.find(x=>x.actor===host).balance,40);
 assert.equal(valid(h,[{...receipt,record_id:'again',key:'player-life:household_expense:again'}]),false);
});
const episode=life('health_episode','cold',{actor,title:'Cold',health_kind:'illness',severity:'moderate',status:'observed',description:'Symptoms'});
const plan=life('care_plan','support',{actor,supporter:host,title:'Rest together',episode_id:'cold',due_at:'1994-08-01 09:00',action_kind:'support',description:'Rest and support',status:'proposed'});
const activity={id:'act',type:'world',activity_version:1,activity_kind:'activity',record_id:'act',key:'activity:activity:act',name:'Rest',description:'Rested',actors:[actor,host],status:'completed',outcome:'Rested together',evidence};
test('health plans require explicit acceptance and same-scene activity; supporter may act independently but cannot cure',()=>{
 const h=[sc('root',[episode,plan])],p=replay(h);
 assert.deepEqual(p.validation_warnings,[]);
 assert.equal(expenseCareView(p,host).care_plans.records[0].episode_id,null);
 assert.equal(expenseCareView(p,'Stranger').care_plans.total,0);
 assert.ok(prepareStoryTurn(h,p,[],{actors:[actor],limit:30}).npc_initiatives.initiatives.some(x=>x.kind==='care_support'&&x.actor===host));
 const done={...plan,status:'completed',completion_kind:'activity',completion_id:'act',outcome:'Rested'};
 assert.equal(valid(h,[activity,done]),false);
 h.push(sc('accept',[{...plan,status:'accepted',outcome:'Agreed'}]));
 assert.equal(valid(h,[done]),false);
 assert.equal(valid(h,[{...activity,actors:[actor]},done]),false);
 assert.equal(valid(h,[activity,done]),true);h.push(sc('complete',[activity,done]));
 const o=playerMenuOverview(replay(h),actor);
 assert.equal(menuSection(o,'health').data.care_plans.records[0].status,'completed');
 assert.equal(o.social_dashboard.health.records[0].status,'observed');
});
