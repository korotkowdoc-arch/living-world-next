import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateScene,validateStateAppend} from '../public/core/continuity.mjs';
import {travelServiceView} from '../public/core/travel-services.mjs';
import {playerMenuOverview,menuActionIntent,MENU_PREFIX,DEFAULT_MENU_SETTINGS} from '../public/core/game-menu.mjs';
import {npcInitiativeView} from '../public/core/npc-initiatives.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
const evidence='Recorded event.';
const actor='Harry',provider='Cafe',currency='GBP';
const ev=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,body:evidence,events,world_time});
const location=place=>({id:'location',type:'character',name:actor,state_patch:{location:place},evidence});
const journey=ev('journey','trip',{actor,title:'Trip',status:'planned',reached:0,stops:[{place:'Home',mode:'walk'},{place:'Station',mode:'walk'},{place:'London',mode:'rail'}]});
const service=ev('venue_service','meal',{actor:provider,place:'Cafe',title:'Meal',category:'food',amount:10,currency,duration_minutes:30,status:'available'});
const quote=ev('discovery','harry-meal',{actor,service_id:'meal',provider,place:'Cafe',title:'Meal',category:'food',amount:10,currency,duration_minutes:30,status:'available'});
const visit=ev('service_visit','lunch',{actor,service_id:'meal',provider,place:'Cafe',title:'Meal',amount:10,currency,status:'accepted'});
const pay={id:'pay',type:'money',actor,counterparty:provider,currency,operation:'transfer',delta:-10,evidence};
const balance={id:'cash',type:'money',actor,currency,operation:'reconcile',delta:0,balance:20,evidence};
const done={...visit,status:'completed',transfer_event_id:'pay',outcome:'A meal was served and eaten.'};
const valid=(history,events)=>validateStateAppend(history,events,evidence).ok;
test('journey progress needs a location observation and cannot skip or rewrite stops',()=>{
 const s=[sc('plan',[journey])];
 assert.equal(valid(s,[{...journey,status:'travelling'}]),false);
 assert.equal(valid(s,[location('Home'),{...journey,status:'travelling'}]),true);
 s.push(sc('start',[location('Home'),{...journey,status:'travelling'}]));
 assert.equal(valid(s,[location('London'),{...journey,status:'arrived',reached:2}]),false);
 assert.equal(valid(s,[location('Station'),{...journey,status:'travelling',reached:1}]),true);
 assert.equal(valid(s,[location('Other'),{...journey,status:'travelling',reached:1}]),false);
 assert.equal(valid(s,[location('Elsewhere'),{...journey,status:'travelling',reached:1,stops:[journey.stops[0],{place:'Elsewhere',mode:'walk'},journey.stops[2]]}]),false);
 s.push(sc('station',[location('Station'),{...journey,status:'travelling',reached:1}]));
 const m=playerMenuOverview(replay(s),actor);
 assert.equal(m.travel.journeys.records[0].next_stop.place,'London');
 assert.equal(menuActionIntent({action:'continue_journey',journey_id:'trip',detail:'Continue'},m).saved,false);
 assert.equal(valid(s,[location('London'),{...journey,status:'arrived',reached:2}]),true);
});
test('catalogue reveals only observed quotes, not new private service prices or other actor records',()=>{
 const s=[sc('known',[service,quote,balance])];
 assert.equal(replay(s).validation_warnings.length,0);
 assert.equal(travelServiceView(replay(s),'Other').catalogue.total,0);
 s.push(sc('price',[{...service,amount:30}]));
 const menu=playerMenuOverview(replay(s),actor);
 assert.equal(menu.travel.catalogue.records[0].amount,10);
 assert.equal(menuActionIntent({action:'request_service',service_id:'meal',detail:'Order'},menu).saved,false);
 assert.equal(valid(s,[visit]),false);
 assert.equal(valid(s,[{...quote,amount:30}]),true);
});
test('accepted service requires unique exact preceding transfer, accepted by the ledger',()=>{
 const history=[sc('known',[service,quote,balance,visit])];
 assert.equal(replay(history).validation_warnings.length,0);
 assert.equal(valid(history,[done]),false);
 assert.equal(valid(history,[done,pay]),false);
 assert.equal(valid(history,[{...pay,delta:-9},done]),false);
 assert.equal(valid(history,[pay,done]),true);
 const p=replay([...history,sc('paid',[pay,done])]);
 assert.equal(travelServiceView(p,actor).visits.records[0].status,'completed');
 assert.equal(p.balances.find(b=>b.actor===actor).balance,10);
 assert.equal(valid([...history,sc('paid',[pay,done])],[pay,done]),false);
 const poor=[sc('poor',[service,quote,{...balance,balance:2},visit])];
 assert.equal(valid(poor,[pay,done]),false);
 const duplicate={...done,id:'second-done',record_id:'second',key:'player-life:service_visit:second'};
 assert.equal(validateScene({body:evidence,events:[pay,done,duplicate]}).ok,false);
});
test('NPC initiative shortlist uses independent motives and is bounded and fair',()=>{
 const c=(actor,key,kind='intention',extra={})=>({actors:[actor],key,title:key,kind,status:'active',source:{scene_id:'a'},certainty:'candidate_only_not_performed',...extra});
 const rows=[c('Harry','player'),c('Lia','l1'),c('Lia','l2'),c('Boris','b1','routine',{timing:'scheduled_window_not_presence'}),c('Clara','c1','production_order',{checks:[{kind:'stock_insufficient'}]}),c('Dora','d1','obligation',{timing:'reached_requires_story'})];
 const low=npcInitiativeView(rows,{player:'Harry',settings:{agency:'low',events:'low'}});
 assert.equal(low.initiatives.length,1);assert.equal(low.initiatives[0].actor,'Dora');
 const high=npcInitiativeView(rows,{player:'Harry',settings:{agency:'high',events:'high'},scenes:[sc('a'),sc('b')]});
 assert.equal(high.initiatives.length,5);
 assert.equal(new Set(high.initiatives.slice(0,4).map(x=>x.actor)).size,4);
 assert.ok(high.initiatives.find(x=>x.actor==='Clara').checks.some(x=>x.kind==='stock_insufficient'));
 assert.equal(npcInitiativeView(rows).initiatives.length,0);
 assert.equal(npcInitiativeView(rows,{player:'Harry',complete:false}).initiatives.length,0);
});
test('story preparation integrates independent NPC plans and menu agency settings',()=>{
 const p={plans:[{actor:'Harry',plan_id:'mine',goal:'Player goal',status:'active'},{actor:'Lia',plan_id:'hers',goal:'Own goal',status:'active'}]};
 const branchId='00000000-0000-4000-8000-000000000001';
 const rules=[{id:'s',active:true,text:MENU_PREFIX+JSON.stringify({kind:'settings',settings:{...DEFAULT_MENU_SETTINGS,agency:'low',events:'low'}})}];
 const turn=prepareStoryTurn([sc('a')],p,rules,{actors:['Harry'],branchId});
 assert.equal(turn.npc_initiatives.initiatives.length,1);assert.equal(turn.npc_initiatives.initiatives[0].actor,'Lia');
 assert.equal(turn.npc_initiatives.budget,1);
});
