import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {marketHomeView} from '../public/core/market-home.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
const evidence='Recorded event.',actor='Harry',provider='Cafe',currency='GBP';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const service=life('venue_service','meal',{actor:provider,title:'Meal',place:'Cafe',category:'food',amount:5,currency,duration_minutes:30,status:'available'});
const discovery=life('discovery','quote',{actor,service_id:'meal',provider,title:'Meal',place:'Cafe',category:'food',amount:5,currency,duration_minutes:30,status:'available'});
const visit=life('service_visit','meal',{actor,provider,service_id:'meal',title:'Meal',place:'Cafe',amount:5,currency,status:'accepted'});
const adjustment=life('market_adjustment','increase',{actor:provider,service_id:'meal',previous_amount:5,amount:7,currency,cause:'cost',description:'Costs increased',status:'recorded'});
const observation=life('market_observation','observed',{actor,service_id:'meal',discovery_id:'quote',provider,title:'Meal',place:'Cafe',amount:5,currency,supply:'unknown',demand:'high',description:'Saw price',status:'recorded'});
test('repricing changes actual catalogue but preserves known quote and accepted order',()=>{
 const h=[sc('start',[service,discovery,visit,observation])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[{...adjustment,actor}]),false);
 assert.equal(valid(h,[{...adjustment,previous_amount:4}]),false);
 assert.equal(valid(h,[adjustment]),true);
 h.push(sc('price',[adjustment]));
 const p=replay(h);
 assert.equal(marketHomeView(p,provider).services.records[0].amount,7);
 assert.equal(marketHomeView(p,actor).observations.records[0].amount,5);
 assert.equal(marketHomeView(p,actor).adjustments.total,0);
 assert.equal(playerMenuOverview(p,actor).travel.visits.records[0].amount,5);
 assert.equal(playerMenuOverview(p,actor).travel.catalogue.records[0].amount,5);
 assert.equal(valid(h,[{...visit,record_id:'new',key:'player-life:service_visit:new'}]),false);
 assert.equal(valid(h,[{...discovery,amount:7},{...observation,id:'new',record_id:'new',key:'player-life:market_observation:new',amount:7}]),true);
 assert.equal(menuActionIntent({action:'adjust_price',service_id:'meal',detail:'Change price'},playerMenuOverview(p,provider)).saved,false);
 assert.throws(()=>menuActionIntent({action:'adjust_price',service_id:'meal',detail:'Change price'},playerMenuOverview(p,actor)));
});
const estate=life('estate','home',{actor,title:'Home',place:'London',estate_kind:'house',status:'owned'});
const item={id:'chair',type:'item',item_id:'chair',name:'Chair',custody_version:1,actor,action:'acquire',evidence};
const furnishing=life('furnishing','chair',{actor,item_id:'chair',home_kind:'estate',home_id:'home',area:'Living room',description:'Chair by the window',status:'placed'});
test('furniture requires custody and access; recovery does not restore placement',()=>{
 const h=[sc('start',[estate,item,furnishing])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid([], [furnishing]),false);
 assert.equal(marketHomeView(replay(h),actor).furnishing.total,1);
 assert.equal(valid(h,[{...furnishing,id:'dup',record_id:'dup',key:'player-life:furnishing:dup'}]),false);
 h.push(sc('lost',[{...item,action:'drop'}]),sc('found',[{...item,action:'recover'}]));
 assert.equal(marketHomeView(replay(h),actor).furnishing.total,0);
 assert.equal(valid(h,[{...furnishing,status:'removed'}]),false);
 assert.equal(valid(h,[furnishing]),true);
 h.push(sc('place',[furnishing]));
 const p=replay(h),overview=playerMenuOverview(p,actor);
 assert.equal(menuSection(overview,'property').data.furnishing.total,1);
 assert.equal(menuActionIntent({action:'remove_furnishing',furnishing_id:'chair',detail:'Move chair'},overview).saved,false);
 const sale=life('estate_sale','sale',{actor,buyer:'Other',estate_id:'home',amount:0,currency,status:'offered'});
 h.push(sc('offer',[sale]),sc('accept',[{...sale,status:'accepted'}]),sc('settle',[{...sale,status:'settled',outcome:'Transferred'}]));
 assert.equal(marketHomeView(replay(h),actor).furnishing.total,0);
 assert.equal(valid(h,[furnishing]),false);
});
