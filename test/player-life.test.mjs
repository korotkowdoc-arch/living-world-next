import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend,needsStatePreflight} from '../public/core/continuity.mjs';
import {playerLifeView,playerLifeError,playerLifeTurnSummary} from '../public/core/player-life.mjs';
import {playerMenuOverview,menuActionIntent} from '../public/core/game-menu.mjs';
const make=(kind,record_id,extra={})=>({id:'event-'+kind+'-'+record_id,type:'world',player_life_version:1,life_kind:kind,record_id,key:'player-life:'+kind+':'+record_id,evidence:'Recorded event.',...extra});
const item=(action,actor='Harry',counterparty)=>({id:'item-'+action,type:'item',custody_version:1,item_id:'coat',name:'Coat',action,actor,...(counterparty?{counterparty}:{}),evidence:'Recorded event.'});
const scene=(id,events)=>({id,body:'Recorded event.',world_time:'1994-08-01',events});
const view=(scenes,actor='Harry')=>playerLifeView(replay(scenes),actor);
const coat=make('garment','coat',{item_id:'coat',slot:'outer',style:'Casual',description:'A coat'});
const outfit=make('outfit','harry',{actor:'Harry',slots:{outer:'coat'}});
const need=make('need','hunger-harry',{actor:'Harry',need:'hunger',status:'urgent',description:'Hungry'});
const letter=make('letter','one',{sender:'Harry',recipient:'Lia',subject:'Hello',message:'A private note',channel:'Post',status:'sent'});
test('unknown needs remain unknown and recorded urgency ranks quick actions',()=>{
 const empty=view([]);assert.ok(empty.needs.every(n=>n.status==='unknown'));
 const v=view([scene('a',[need])]);
 assert.equal(v.needs.find(n=>n.need==='hunger').status,'urgent');
 assert.equal(v.quick_actions[0].action,'eat');assert.equal(v.quick_actions[0].availability,'requires_scene_check');
 assert.equal(playerLifeError({...need,status:90})!==null,true);
 assert.equal(needsStatePreflight([need]),true);
 assert.equal(validateStateAppend([scene('a',[need])],[make('need','another',{actor:'Harry',need:'hunger',status:'comfortable',description:'Full'})],'Recorded event.').ok,false);
});
test('wardrobe requires real custody, slot match, and explicit re-equipping after transfer',()=>{
 const root=scene('root',[item('acquire'),coat,outfit]);
 assert.equal(replay([root]).validation_warnings.length,0);
 assert.equal(view([root]).wardrobe.records[0].equipped,true);
 assert.equal(validateStateAppend([root],[{...outfit,slots:{head:'coat'}}],'Recorded event.').ok,false);
 const away=scene('away',[item('transfer','Harry','Lia')]);
 assert.deepEqual(view([root,away]).outfit.slots,{});assert.equal(view([root,away]).wardrobe.total,0);
 assert.equal(view([root,away],'Lia').wardrobe.records[0].equipped,false);
 assert.equal(validateStateAppend([root,away],[outfit],'Recorded event.').ok,false);
 const back=scene('back',[item('transfer','Lia','Harry')]);
 assert.equal(view([root,away,back]).wardrobe.records[0].equipped,false);
 assert.equal(view([root,away,back,scene('again',[outfit])]).wardrobe.records[0].equipped,true);
 assert.equal(view([root]).wardrobe.records[0].equipped,true);
});
test('letters retain actual stages and hide content and unconfirmed feedback',()=>{
 const sent=scene('s',[letter]);
 const delivered=scene('d',[{...letter,status:'delivered',sender_notified:true}]);
 const read=scene('r',[{...letter,status:'read'}]);
 assert.equal(view([sent],'Lia').letters.incoming.total,0);
 const incoming=view([sent,delivered],'Lia').letters.incoming.records[0];
 assert.equal(incoming.message,null);assert.equal(incoming.subject,null);
 assert.equal(view([sent,delivered,read],'Lia').letters.incoming.records[0].message,letter.message);
 const outgoing=view([sent,delivered,read]).letters.outgoing.records[0];
 assert.equal(outgoing.status,'delivered');assert.equal(outgoing.source.scene_id,'d');
 assert.equal(validateStateAppend([], [{...letter,status:'read'}],'Recorded event.').ok,false);
 assert.equal(validateStateAppend([sent],[{...letter,status:'delivered',message:'Changed'}],'Recorded event.').ok,false);
 assert.equal(playerLifeTurnSummary(replay([sent,delivered]),'Lia').unread_letters,1);
});
test('life menu actions are only intentions with validated own task and inbox targets',()=>{
 const p=replay([scene('s',[need,letter])]);
 p.plans=[{actor:'Harry',plan_id:'work',goal:'Find work',status:'active'}];
 const menu=playerMenuOverview(p,'Harry');
 assert.equal(menuActionIntent({action:'eat',detail:'Find food'},menu).saved,false);
 assert.equal(menuActionIntent({action:'pause_task',task_id:'plan:work',detail:'Pause'},menu).task_id,'plan:work');
 assert.throws(()=>menuActionIntent({action:'resume_task',task_id:'plan:work',detail:'Resume'},menu));
 assert.throws(()=>menuActionIntent({action:'read_letter',letter_id:'one',detail:'Read'},menu));
 const inbox=playerMenuOverview(replay([scene('s',[letter]),scene('d',[{...letter,status:'delivered'}])]),'Lia');
 assert.equal(menuActionIntent({action:'read_letter',letter_id:'one',detail:'Read'},inbox).saved,false);
});
