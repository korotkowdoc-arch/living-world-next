import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {homeView} from '../public/core/home-systems.mjs';
import {playerMenuOverview,menuActionIntent} from '../public/core/game-menu.mjs';
import {playerCalendar,planTimeAdvance} from '../public/core/life-calendar.mjs';
const actor='Harry',currency='GBP',evidence='Recorded event.';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const dyn=(dynamics_kind,record_id,extra)=>({id:dynamics_kind+'-'+record_id,type:'world',dynamics_version:1,dynamics_kind,record_id,key:'dynamics:'+dynamics_kind+':'+record_id,description:'Recorded',evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,body:evidence,events,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const rent=dyn('economic_agreement','rent',{actor,counterparty:'Owner',title:'Rent',place:'Flat',agreement_kind:'rent',status:'active',amount:50,currency});
const schedule=dyn('payment_schedule','rent',{actor,counterparty:'Owner',title:'Rent',payment_kind:'rent',status:'active',amount:50,currency,starts_on:'1994-08-01',every_days:30});
const lease=life('lease','flat',{actor,landlord:'Owner',place:'Flat',title:'Flat',agreement_id:'rent',schedule_id:'rent',status:'active'});
const budget=life('budget','budget',{actor,title:'Monthly budget',currency,monthly_limit:60,savings_target:100,status:'active'});
test('housing references exact rent terms and budgets count actual transactions not balance reconciliations',()=>{
 const cash={id:'cash',type:'money',actor,currency,operation:'reconcile',delta:0,balance:100,evidence};
 const pay={id:'pay',type:'money',actor,counterparty:'Owner',currency,operation:'transfer',delta:-50,evidence};
 const condition=life('home_condition','wall',{actor,lease_id:'flat',area:'Wall',status:'damaged',description:'Needs repair'});
 assert.equal(valid([],[lease]),false);
 assert.equal(valid([sc('s',[rent,schedule])],[{...lease,landlord:'Other'}]),false);
 const h=[sc('s',[rent,schedule,lease,budget,cash,condition])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[{...lease,status:'ended'}]),false);
 assert.equal(valid(h,[{...budget,id:'dup',record_id:'dup',key:'player-life:budget:dup'}]),false);
 h.push(sc('paid',[pay]));const p=replay(h),v=homeView(p,actor,'1994-08-01 12:00');
 assert.equal(v.housing.records[0].rent.amount,50);
 assert.equal(v.housing.records[0].conditions[0].status,'damaged');
 assert.equal(v.budgets.records[0].recorded_expense,50);assert.equal(v.budgets.records[0].balance,50);
 assert.equal(homeView(p,'Owner','1994-08-01').housing.total,0);
 assert.equal(p.budget_flows.find(x=>x.actor==='Owner').income,50);
 assert.equal(valid(h,[{...rent,status:'settled',outcome:'Closed'},{...schedule,status:'ended'},{...lease,status:'ended'}]),true);
 assert.equal(menuActionIntent({action:'repair_home',lease_id:'flat',detail:'Repair wall'},playerMenuOverview(p,actor)).saved,false);
});
const service=life('venue_service','room',{actor:'Hotel',place:'Hotel',title:'Room',category:'lodging',amount:0,currency,duration_minutes:1440,status:'available'});
const slot=life('capacity_slot','night',{actor:'Hotel',service_id:'room',resource:'Single rooms',starts_at:'1994-08-01 15:00',ends_at:'1994-08-02 11:00',capacity:1,status:'open'});
const visit=(id,actor)=>life('service_visit',id,{actor,provider:'Hotel',service_id:'room',place:'Hotel',title:'Room',amount:0,currency,status:'accepted'});
const reservation=(id,actor,visit_id)=>life('reservation',id,{actor,slot_id:'night',visit_id,units:1,status:'reserved'});
test('reservations cannot exceed slot capacity and only matching cancelled orders release a seat',()=>{
 const h=[sc('s',[service,slot,visit('a',actor),visit('b','Lia'),reservation('a',actor,'a')])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[reservation('b','Lia','b')]),false);
 assert.equal(valid(h,[{...reservation('a',actor,'a'),status:'cancelled'}]),false);
 assert.equal(valid(h,[{...slot,id:'other',record_id:'other',key:'player-life:capacity_slot:other'}]),false);
 assert.equal(valid(h,[{...visit('a',actor),status:'cancelled'},{...reservation('a',actor,'a'),status:'cancelled'},reservation('b','Lia','b')]),true);
 const p=replay(h);
 assert.equal(homeView(p,'Hotel').capacity.records[0].allocated,1);
 assert.equal(homeView(p,actor).reservations.total,1);
 assert.equal(homeView(p,'Lia').reservations.total,0);
 assert.ok(playerCalendar(p,actor,'1994-08-01 09:00').entries.some(x=>x.kind==='reservation'));
});
const group={id:'school',type:'world',social_record_version:1,social_kind:'group',record_id:'school',key:'social:group:school',name:'School',purpose:'Education',status:'active',evidence};
const institution=dyn('institution','school',{name:'School',group_id:'school',function:'Education',place:'School',status:'operating'});
const enrollment=life('enrollment','course',{actor,institution_id:'school',title:'Magic',place:'School',status:'enrolled'});
const exam=life('assessment','exam',{actor,enrollment_id:'course',title:'Test',starts_at:'1994-08-01 10:00',ends_at:'1994-08-01 11:00',status:'scheduled'});
const skill={id:'skill',type:'world',growth_version:1,growth_kind:'skill',record_id:'spell',key:'growth:skill:spell',actor,name:'Spells',status:'learning',description:'Learning',evidence};
const practice=life('practice_record','practice',{actor,skill_id:'spell',origin_kind:'assessment',origin_id:'exam',description:'Practised spells',status:'recorded'});
test('education, skill practice and known reputation require recorded sources',()=>{
 const known=life('reputation','known',{actor,group_id:'school',observer:'Teacher',description:'Good work',status:'positive',known_to_actor:true});
 const hidden=life('reputation','hidden',{actor,group_id:'school',observer:'Other',description:'Private opinion',status:'negative',known_to_actor:false});
 const h=[sc('school',[group,institution,enrollment,exam,skill,known,hidden])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[practice]),false);
 assert.equal(valid(h,[{...exam,status:'passed',outcome:'Passed'},practice]),true);
 assert.equal(valid(h,[{...exam,status:'passed',outcome:'Passed',starts_at:'1994-08-01 09:30'}]),false);
 const p=replay(h);
 assert.equal(homeView(p,actor).reputation.total,1);
 assert.equal(planTimeAdvance(h,p,actor,'1994-08-02 09:00').gate.kind,'assessment');
 assert.equal(menuActionIntent({action:'take_assessment',assessment_id:'exam',detail:'Take test'},playerMenuOverview(p,actor)).saved,false);
 h.push(sc('exam',[{...exam,status:'passed',outcome:'Passed'},practice]));
 assert.equal(homeView(replay(h),actor).practice.total,1);
 assert.equal(replay(h).worldFacts.find(x=>x.key===skill.key).status,'learning');
});
