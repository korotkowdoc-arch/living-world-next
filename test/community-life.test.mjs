import test from 'node:test';
import assert from 'node:assert/strict';
import {communityIndex,communityTransition,communityWindows,validateCommunityAction} from '../public/core/community-life.mjs';
import {playerCalendar} from '../public/core/life-calendar.mjs';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {playerMenuOverview,menuSection} from '../public/core/game-menu.mjs';
const source={scene_id:'s',event_id:'e'};
const ev=(kind,id,fields)=>({id:'ev_'+id,type:'world',player_life_version:1,life_kind:kind,record_id:id,key:'player-life:'+kind+':'+id,evidence:'Confirmed event.',...fields});
const group=g=>({id:'group_'+g,type:'world',social_record_version:1,social_kind:'group',record_id:g,key:'social:group:'+g,name:g,purpose:'Sport',status:'active',evidence:'Confirmed event.'});
const mem=(g,a)=>({id:'mem_'+g+'_'+a,type:'world',social_record_version:1,social_kind:'membership',record_id:g+'_'+a,key:'social:membership:'+g+'_'+a,group_id:g,actor:a,status:'member',evidence:'Confirmed event.'});
const event=ev('community_event','match',{actor:'Coach',group_id:'league',title:'Match',description:'A scheduled match',place:'Pitch',event_kind:'sport',series:'Autumn',home_group_id:'red',away_group_id:'blue',capacity:1,starts_at:'2000-09-01 10:00',ends_at:'2000-09-01 12:00',status:'scheduled'});
const invite=(a,i)=>ev('community_participation',i,{actor:a,organizer:'Coach',event_id:'match',role:'athlete',team_id:'red',status:'invited'});
const initial=[group('league'),group('red'),group('blue'),mem('league','Coach'),mem('red','Hero'),mem('red','Other')];
const rows=xs=>new Map(xs.map(r=>[r.key,{...r,source}]));
const put=(r,e)=>{assert.equal(communityTransition(r,e),null);r.set(e.key,{...e,source});};
const scene=(id,events)=>({id,events,body:'Confirmed event.',world_time:'2000-09-01 09:00'});
test('recorded community event has separate invitation, acceptance, capacity and actual attendance',()=>{
 const r=rows(initial),a=invite('Hero','a'),b=invite('Other','b');
 assert.ok(communityTransition(r,{...event,actor:'Hero'}));put(r,event);put(r,a);put(r,b);
 assert.equal(communityWindows({worldFacts:[...r.values()]},'Hero').length,0);
 const accepted={...a,status:'accepted',outcome:'Accepted'};put(r,accepted);
 assert.ok(communityTransition(r,{...b,status:'accepted',outcome:'Accepted'}));
 assert.ok(communityTransition(r,{...accepted,status:'attended',outcome:'Attended'}));
 const p={worldFacts:[...r.values()]};assert.equal(communityWindows(p,'Hero').length,1);
 assert.ok(playerCalendar(p,'Hero','2000-09-01 09:00').entries.some(e=>e.kind==='community_event'));
 put(r,{...event,status:'in_progress'});put(r,{...accepted,status:'attended',outcome:'Attended'});
 assert.equal(communityWindows({worldFacts:[...r.values()]},'Hero').length,0);
});
test('only actual completed match yields scores; reports expose only observed result, not hidden future games',()=>{
 const r=rows(initial);put(r,event);put(r,{...event,status:'in_progress'});
 const result=ev('community_result','score',{actor:'Coach',event_id:'match',description:'Private result',home_score:30,away_score:10,status:'recorded'});
 assert.ok(communityTransition(r,result));put(r,{...event,status:'completed',outcome:'Played'});put(r,result);
 const view=()=>communityIndex({worldFacts:[...r.values()]}).view('Hero');
 assert.equal(view().results.total,0);
 const report=ev('community_report','report',{actor:'Hero',reporter:'Coach',result_id:'score',event_id:'match',description:'Red won 30–10',home_score:30,away_score:10,status:'received'});put(r,report);
 assert.equal(view().results.records[0].description,'Red won 30–10');assert.doesNotMatch(JSON.stringify(view()),/Private result/);
 assert.equal(view().standings.records[0].recorded_matches,1);assert.equal(view().standings.records[0].teams[0].won,1);
 assert.ok(communityTransition(r,{...result,key:'player-life:community_result:duplicate',record_id:'duplicate'}));
});
test('replay, menu and NPC candidates share records, hidden participants and invalid IDs are unavailable',()=>{
 const a=invite('Hero','a'),h=[scene('s1',initial),scene('s2',[event,a])],p=replay(h);
 assert.equal(p.validation_warnings.length,0);
 assert.equal(validateStateAppend(h,[{...a,id:'accept',status:'accepted',outcome:'Accepted'}],'Confirmed event.').ok,true);
 const o=playerMenuOverview(p,'Hero','2000-09-01 09:00',{scenes:h});
 assert.equal(menuSection(o,'education').data.campus_events.participation.total,1);
 assert.doesNotThrow(()=>validateCommunityAction({action:'community_rsvp',community_record_id:'a'},o));
 assert.throws(()=>validateCommunityAction({action:'community_rsvp',community_record_id:'hidden'},o));
 assert.equal(communityIndex(p).view('Other').participation.total,0);
 assert.ok(communityIndex(p).opportunities().some(x=>x.kind==='community_rsvp'&&x.row.actor==='Hero'));
 assert.equal(communityIndex(p,{complete:false}).opportunities().length,0);
});

test('report without a communicated score does not disclose numbers or standings; hidden cancellation does not change player calendar',()=>{
 const r=rows(initial),a=invite('Hero','a');put(r,event);put(r,a);put(r,{...a,status:'accepted',outcome:'Accepted'});
 put(r,{...event,status:'cancelled',outcome:'Cancelled privately'});
 assert.equal(communityWindows({worldFacts:[...r.values()]},'Hero').length,1);
 assert.equal(communityWindows({worldFacts:[...r.values()]}).length,0);
 put(r,{...a,status:'cancelled',outcome:'Notice received'});
 assert.equal(communityWindows({worldFacts:[...r.values()]},'Hero').length,0);
 const s=rows(initial);put(s,event);put(s,{...event,status:'in_progress'});put(s,{...event,status:'completed',outcome:'Played'});
 const result=ev('community_result','score',{actor:'Coach',event_id:'match',description:'Secret score',home_score:30,away_score:10,status:'recorded'});put(s,result);
 const report=ev('community_report','report',{actor:'Hero',reporter:'Coach',result_id:'score',event_id:'match',description:'Red won',status:'received'});
 assert.ok(communityTransition(s,{...report,home_score:99,away_score:0}));put(s,report);
 const v=communityIndex({worldFacts:[...s.values()]}).view('Hero');assert.equal(v.results.records[0].home_score,null);assert.equal(v.standings.total,0);
});
