import test from 'node:test';
import assert from 'node:assert/strict';
import {buildLongLifeIndex,backgroundTimeReview} from '../public/core/npc-long-life.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
import {characterStateView} from '../public/core/character-state.mjs';
const time='2000-01-01 08:00',target='2000-03-01 08:00';
const scene={id:'s',world_time:time,events:[]};
const src={scene_id:'s',event_id:'e',world_time:time};
const p=(name,fields={})=>({name,state_fields:Object.entries(fields).map(([field,value])=>({field,value,source:src}))});
const world=(key,extra)=>({key,record_id:key.split(':').at(-1),source:src,...extra});
const group=world('social:group:club',{social_record_version:1,social_kind:'group',name:'Music club',status:'active'});
const member=(a,status='member')=>world('social:membership:'+a,{social_record_version:1,social_kind:'membership',actor:a,group_id:'club',status});
const habit=(a,name,status='active')=>world('activity:habit:'+a,{activity_version:1,activity_kind:'habit',actor:a,name,status});
const project=world('growth:project:book',{growth_version:1,growth_kind:'project',actor:'Lia',title:'Book',status:'active',next_step:'Write chapter',due_at:'2000-02-01 08:00'});
const experience=world('activity:activity:concert',{activity_version:1,activity_kind:'activity',actors:['Lia','Tom'],name:'Concert',status:'completed',outcome:'Played music'});
const causal=world('growth:cause:link',{growth_version:1,growth_kind:'cause',status:'claimed',actor:'Lia',from_key:experience.key,to_key:project.key,description:'Inspired by concert'});
const thread=world('social:thread:music',{social_record_version:1,social_kind:'thread',actors:['Lia','Tom'],title:'Independent rehearsal',status:'open'});
const projection={people:[p('Harry'),p('Lia',{preference:'Music',aversion:'Crowds',personal_goal:'Book'}),p('Tom',{preference:'Music'}),p('Ada',{aversion:'Music'})],worldFacts:[group,member('Lia'),member('Tom'),member('Ada','left'),habit('Ada','Music'),project,experience,causal,thread],plans:[]};
test('long-life profiles preserve separate interests, goals, social circles, actual experience and qualified cause claims',()=>{
 const before=JSON.stringify(projection),index=buildLongLifeIndex([scene],projection);
 const lia=index.view('Lia',{clock:target});
 assert.equal(lia.interests.total,2);
 assert.ok(lia.goals.records.some(x=>x.kind==='project'&&x.next_step==='Write chapter'));
 assert.ok(lia.threads.records.some(x=>x.title==='Independent rehearsal'));
 assert.equal(lia.circles.records[0].recorded_active_members,2);
 assert.equal(lia.experience.records[0].title,'Concert');
 assert.equal(lia.causes.records[0].status,'claimed');
 assert.equal(index.view('Tom').causes.total,0);
 assert.equal(lia.calendar_days_since_record,60);
 assert.equal(characterStateView(projection,'Lia',{scenes:[scene]}).long_life.goals.total,2);
 assert.equal(JSON.stringify(projection),before);
 assert.equal(buildLongLifeIndex([scene],projection,{complete:false}).view('Lia').memory_complete,false);
});
test('interest seeds and possible shared activities respect aversions, boundaries and existing projects',()=>{
 const opportunities=buildLongLifeIndex([scene],projection).opportunities();
 assert.ok(opportunities.some(x=>x.kind==='interest_project'&&x.row.actor==='Lia'));
 assert.ok(opportunities.some(x=>x.kind==='shared_interest'&&x.row.actor==='Lia'&&x.row.counterparty==='Tom'));
 assert.ok(!opportunities.some(x=>x.row.actor==='Ada'||x.row.counterparty==='Ada'));
 const blocked={...projection,relationships:[{a:'Tom',b:'Lia',relationship_fields:[{field:'boundary',value:'no_contact'}],source:src}],worldFacts:[...projection.worldFacts,world('growth:project:music',{growth_version:1,growth_kind:'project',actor:'Lia',title:'Music',status:'active'})]};
 const next=buildLongLifeIndex([scene],blocked).opportunities();
 assert.ok(!next.some(x=>x.kind==='shared_interest'));
 assert.ok(!next.some(x=>x.kind==='interest_project'&&x.row.actor==='Lia'));
 assert.deepEqual(buildLongLifeIndex([scene],projection,{complete:false}).opportunities(),[]);
});
test('long jumps separate current segment, later dates, recurrence and protected player choices',()=>{
 const c=(actor,kind,review_at)=>({actors:[actor],kind,key:actor+kind,title:kind,review_at,source:src});
 const candidates=[c('Lia','lesson','2000-01-01 10:00'),c('Tom','appointment','2000-02-01 12:00'),c('Harry','task','2000-01-01 09:00'),c('Lia','routine',null)];
 const result=backgroundTimeReview(candidates,{clock:time,target,segmentUntil:'2000-01-01 12:00',protectedActors:['Harry'],pace:'fast'});
 assert.equal(result.segment_until,'2000-01-01 12:00');
 assert.equal(result.due.total,1);assert.equal(result.later.total,1);assert.equal(result.recurring.total,1);
 assert.ok(result.minimum_remaining_segments>1);
 assert.equal(backgroundTimeReview(candidates,{clock:time,target,protectedActors:['Harry'],pending:true}).status,'player_choice_pending');
 assert.equal(backgroundTimeReview(candidates,{clock:time,target,protectedActors:[]}),null);
});
test('turn uses long-life context, and does not prioritize a distant NPC deadline as a current action',()=>{
 const turn=prepareStoryTurn([scene],projection,[],{actors:['Harry'],target_time:target,limit:30});
 assert.ok(turn.background_time_review);
 assert.ok(turn.background_time_review.later.records.some(x=>x.actor==='Lia'&&x.kind==='project'));
 assert.ok(!turn.npc_initiatives.initiatives.some(x=>x.kind==='project'));
 assert.ok(turn.npc_initiatives.initiatives.every(x=>x.actor!=='Harry'));
 assert.ok(turn.actor_context.find(x=>x.actor==='Lia')?.life_interests?.length);
 assert.ok(turn.candidates.some(x=>x.kind==='interest_project'));
});
test('large shared-interest groups yield bounded candidates per actor',()=>{
 const people=Array.from({length:1000},(_,i)=>p('NPC '+i,{preference:'Music'}));
 const result=buildLongLifeIndex([scene],{people}).opportunities();
 assert.equal(result.filter(x=>x.kind==='shared_interest').length,1000);
 assert.equal(result.filter(x=>x.kind==='interest_project').length,1000);
});
