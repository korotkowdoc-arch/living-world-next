import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {curriculumView} from '../public/core/curriculum-supply.mjs';
import {playerMenuOverview,menuSection,menuActionIntent} from '../public/core/game-menu.mjs';
import {playerCalendar,planTimeAdvance} from '../public/core/life-calendar.mjs';
import {prepareStoryTurn} from '../public/core/story-turn.mjs';
const evidence='Recorded event.',actor='Harry',currency='GBP';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const dyn=(dynamics_kind,record_id,extra)=>({id:dynamics_kind+'-'+record_id,type:'world',dynamics_version:1,dynamics_kind,record_id,key:'dynamics:'+dynamics_kind+':'+record_id,description:'Recorded',evidence,...extra});
const group=(record_id,name)=>({id:'group-'+record_id,type:'world',social_record_version:1,social_kind:'group',record_id,key:'social:group:'+record_id,name,purpose:name,status:'active',evidence});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const institution=dyn('institution','school',{name:'School',group_id:'school',function:'Education',place:'School',status:'operating'});
const enrollment=life('enrollment','course',{actor,institution_id:'school',title:'Magic',place:'School',status:'enrolled'});
const program=life('study_program','program',{actor:'School',institution_id:'school',title:'Magic',place:'School',modules:[{id:'spell',title:'Spells'},{id:'potions',title:'Potions'}],status:'active'});
const join=life('program_enrollment','join',{actor,program_id:'program',enrollment_id:'course',status:'active'});
const exam=(id,title)=>life('assessment',id,{actor,enrollment_id:'course',title,starts_at:'1994-08-01 10:00',ends_at:'1994-08-01 11:00',status:'scheduled'});
const result=(id,module_id,assessment_id,status='passed')=>life('module_result',id,{actor,program_enrollment_id:'join',module_id,assessment_id,status});
const credential=life('qualification','certificate',{actor,program_enrollment_id:'join',title:'Magic certificate',description:'Awarded',status:'awarded'});
test('program requires every module, distinct assessments, matching enrollment and explicit qualification',()=>{
 const a=exam('a','Spells'),b=exam('b','Potions'),h=[sc('root',[group('school','School'),institution,enrollment,program,join,a,b])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[credential]),false);
 assert.equal(valid(h,[{...enrollment,status:'completed'},{...join,status:'completed'}]),false);
 assert.equal(valid(h,[result('r','spell','a')]),false);
 h.push(sc('first',[{...a,status:'passed',outcome:'Passed'},result('r','spell','a')]));
 assert.equal(valid(h,[result('dup','potions','a')]),false);
 assert.equal(valid(h,[{...enrollment,status:'completed'}]),false);
 h.push(sc('second',[{...b,status:'passed',outcome:'Passed'},result('r2','potions','b')]));
 assert.equal(valid(h,[{...enrollment,status:'completed'}]),false);
 assert.equal(valid(h,[{...enrollment,status:'completed'},{...join,status:'completed'},credential]),true);
 h.push(sc('finish',[{...enrollment,status:'completed'},{...join,status:'completed'},credential]));
 const view=curriculumView(replay(h),actor);
 assert.equal(view.enrollments.records[0].modules.filter(m=>m.passed).length,2);
 assert.equal(view.qualifications.total,1);
 assert.equal(menuSection(playerMenuOverview(replay(h),actor),'education').data.qualifications.total,1);
 assert.equal(valid(h,[{...credential,record_id:'dup',key:'player-life:qualification:dup'}]),false);
 assert.equal(valid(h,[{...credential,status:'revoked',description:'Revoked'}]),true);
});
const enterprise=dyn('enterprise','shop',{actor,title:'Shop',place:'Shop',group_id:'shop',business_kind:'Retail',status:'operating'});
const agreement=dyn('economic_agreement','agreement',{actor,counterparty:'Supplier',title:'Supply',agreement_kind:'other',amount:30,currency,status:'proposed'});
const stock_lines=[{product_id:'bread',unit:'piece',quantity:3}];
const contract=life('supply_contract','supply',{actor,enterprise_id:'shop',agreement_id:'agreement',supplier:'Supplier',title:'Bread',amount:30,currency,due_at:'1994-08-02 10:00',stock_lines,status:'proposed'});
const cash={id:'cash',type:'money',actor,currency,delta:0,balance:50,operation:'reconcile',evidence};
const count=(holder,quantity,id)=>dyn('stock_operation',id,{actor:holder,stock_action:'count',stock_lines:[{...stock_lines[0],quantity}],status:'recorded'});
const transfer=dyn('stock_operation','delivery',{actor:'Supplier',counterparty:actor,stock_action:'transfer',stock_lines,status:'recorded'});
const pay={id:'pay',type:'money',actor,counterparty:'Supplier',currency,delta:-30,operation:'transfer',evidence};
const settled={...contract,status:'settled',transfer_event_id:'pay',stock_event_id:transfer.id,outcome:'Delivered'};
const close={...agreement,status:'settled',outcome:'Delivered'};
test('supply contract binds existing agreement to exact money and stock transfers, calendar and NPC',()=>{
 const h=[sc('root',[group('shop','Shop'),enterprise,agreement,contract,cash,count('Supplier',5,'stock'),count(actor,0,'own')])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[{...agreement,status:'active'}]),false);
 assert.equal(valid(h,[{...agreement,status:'active'},{...contract,status:'active'}]),true);
 h.push(sc('accept',[{...agreement,status:'active'},{...contract,status:'active'}]));
 const p=replay(h);
 assert.equal(curriculumView(p,'Supplier').supplies.total,1);
 assert.equal(curriculumView(p,'Stranger').supplies.total,0);
 assert.ok(playerCalendar(p,'Supplier','1994-08-01 09:00').entries.some(x=>x.kind==='supply_contract'));
 assert.equal(planTimeAdvance(h,p,actor,'1994-08-03 09:00',{pace:'fast'}).gate.kind,'supply_contract');
 const turn=prepareStoryTurn(h,p,[],{actors:[actor],limit:30});
 assert.ok(turn.npc_initiatives.initiatives.some(x=>x.kind==='supply_supplier'&&x.actor==='Supplier'));
 assert.equal(menuActionIntent({action:'settle_supply',contract_id:'supply',detail:'Deliver'},playerMenuOverview(p,actor)).saved,false);
 assert.equal(valid(h,[close]),false);
 assert.equal(valid(h,[pay,close,settled]),false);
 assert.equal(valid(h,[transfer,{...pay,delta:-29},close,settled]),false);
 assert.equal(valid(h,[transfer,pay,close,settled]),true);
 h.push(sc('done',[transfer,pay,close,settled]));
 const end=replay(h);
 assert.equal(end.balances.find(x=>x.actor===actor).balance,20);
 assert.equal(end.stock.find(x=>x.holder===actor).quantity,3);
 assert.equal(end.stock.find(x=>x.holder==='Supplier').quantity,2);
 assert.equal(curriculumView(end,actor).supplies.records[0].status,'settled');
 assert.equal(valid(h,[transfer,pay,close,settled]),false);
});
