import test from 'node:test';
import assert from 'node:assert/strict';
import {archiveIndex,archiveShapeError} from '../public/core/world-archive.mjs';
import {replay,validateStateAppend,needsStatePreflight} from '../public/core/continuity.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
const evidence='Confirmed fictional event.';
const sc=(id,events)=>({id,body:evidence,events,world_time:'1998-09-01 09:00'});
const a=(k,i,fields)=>({id:k+'_'+i,type:'world',archive_version:1,archive_kind:k,record_id:i,key:'archive:'+k+':'+i,evidence,...fields});
const book=a('document','book',{actor:'Author',title:'Resonance',author:'Author',edition:'1',summary:'Fictional theory',document_kind:'textbook',status:'published',contents:[{id:'first',title:'First chapter'},{id:'second',title:'Second chapter'}]});
const exact='Первый абзац.\n\nВторой абзац — сохранённый текст.\n';
const part=a('part','part1',{actor:'Author',document_id:'book',part_id:'first',text:exact,summary:'Two paragraphs',status:'recorded'});
const access=a('access','grant',{actor:'Author',document_id:'book',reader:'Hero',basis:'Borrowed copy',status:'granted'});
const reading=a('reading','read1',{actor:'Hero',document_id:'book',part_id:'first',reflection:'Curious',status:'read'});
const h=[sc('s1',[book,part,access])];
const ix=history=>archiveIndex(history,replay(history));
test('document text stays byte-for-byte, access and first read are independent',()=>{
 const x=ix(h);
 assert.deepEqual(x.warnings,[]);
 assert.equal(x.view('Hero').library.total,1);
 assert.equal(x.view('Stranger').library.total,0);
 assert.equal(x.open('Hero','book','first').part.text,null);
 assert.equal(x.open('Hero','book','first').part.requires_first_read,true);
 assert.equal(x.open('Hero','book','second').part.requires_authoring,true);
 assert.equal(x.authoring('Hero','book','first').part.text,exact);
 assert.throws(()=>x.authoring('Stranger','book','first'));
 assert.throws(()=>x.open('Stranger','book'));
 const next=[...h,sc('s2',[reading])],y=ix(next);
 assert.equal(y.open('Hero','book','first').part.text,exact);
 assert.equal(y.open('Hero','book').read_count,1);
 assert.equal(y.open('Hero','book','first').part.reflection,'Curious');
 assert.equal(ix(h).open('Hero','book','first').part.text,null);
 assert.equal(validateStateAppend(next,[{...part,text:'A rewrite'}],evidence).ok,false);
 assert.equal(validateStateAppend(next,[{...part,record_id:'duplicate',key:'archive:part:duplicate'}],evidence).ok,false);
 assert.equal(validateStateAppend(next,[{...book,title:'New title'}],evidence).ok,false);
 assert.equal(validateStateAppend(h,[{...reading,part_id:'second'}],evidence).ok,false);
 assert.ok(needsStatePreflight([part]));
 assert.ok(archiveShapeError({...part,archive_version:2}));
});
test('revocation retains read text but not unread chapters, book versions independent',()=>{
 const h2=[...h,sc('s2',[reading]),sc('s3',[{...access,status:'revoked'}])];
 const x=ix(h2);
 assert.equal(x.open('Hero','book').access,'previously_read');
 assert.equal(x.open('Hero','book').contents.length,1);
 assert.equal(x.open('Hero','book','first').part.text,exact);
 assert.throws(()=>x.open('Hero','book','second'));
 assert.throws(()=>x.authoring('Hero','book','second'));
 const newer={...book,id:'new',record_id:'new',key:'archive:document:new',edition:'2',previous_id:'book'};
 const next=[...h2,sc('s4',[newer])];
 assert.deepEqual(ix(next).warnings,[]);
 assert.equal(ix(next).open('Author','book','first').part.text,exact);
 assert.equal(ix(next).open('Author','new','first').part.text,null);
 assert.throws(()=>ix(next).open('Hero','new'));
});
test('bookmarks, private notes, immutable published reviews, publication completion',()=>{
 const bookmark=a('bookmark','mark',{actor:'Hero',document_id:'book',part_id:'second',status:'active'});
 const note=a('note','note',{actor:'Hero',document_id:'book',part_id:'first',text:'Private reflection',status:'active'});
 const review=a('review','review',{actor:'Hero',document_id:'book',text:'Excellent',status:'private'});
 const pub=a('publication','pub',{actor:'Author',document_id:'book',publisher:'Press',channel:'Journal',status:'proposed'});
 const h2=[...h,sc('s2',[reading,bookmark,note,review,pub]),sc('s3',[{...pub,status:'accepted'}])];
 assert.equal(ix(h2).open('Hero','book','second').part.bookmarked,true);
 assert.equal(ix(h2).open('Hero','book').notes[0].text,'Private reflection');
 assert.equal(ix(h2).open('Author','book').notes.length,0);
 assert.equal(ix(h2).open('Author','book').reviews.length,0);
 assert.equal(validateStateAppend(h2,[{...pub,status:'published'}],evidence).ok,false);
 const p2={...part,id:'p2',key:'archive:part:p2',record_id:'p2',part_id:'second',text:'Second chapter'};
 const next=[...h2,sc('s4',[p2,{...pub,status:'published'},{...review,status:'shared'}])];
 assert.deepEqual(ix(next).warnings,[]);
 assert.equal(ix(next).open('Author','book').reviews[0].text,'Excellent');
 assert.equal(validateStateAppend(next,[{...review,status:'shared',text:'Changed'}],evidence).ok,false);
});
test('menu only has metadata and focused readers, actions pin accessible parts',()=>{
 const p=replay(h),o=playerMenuOverview(p,'Hero',null,{scenes:h});
 assert.equal(menuSection(o,'library').data.total,1);
 assert.equal(JSON.stringify(o).includes(exact),false);
 assert.equal(o.archive_reader('book','first').part.text,null);
 const result=menuActionIntent({action:'read_document',document_id:'book',part_id:'first',detail:'Read chapter'},o);
 assert.equal(result.document_id,'book');assert.equal(result.part_id,'first');
 assert.throws(()=>menuActionIntent({action:'write_document_part',document_id:'book',part_id:'second',detail:'Write'},o));
 assert.throws(()=>menuActionIntent({action:'read_document',document_id:'book',part_id:'not_real',detail:'Read'},o));
 assert.throws(()=>menuActionIntent({action:'review_document',document_id:'book',detail:'Review'},o));
 assert.equal(ix(h).view('Hero',{limit:1}).library.total,1);
 const incomplete=archiveIndex(h,p,{complete:false});
 assert.equal(incomplete.view('Hero').memory_complete,false);
 assert.throws(()=>incomplete.open('Hero','book'));
});
