import test from 'node:test';
import assert from 'node:assert/strict';
import {replay,validateStateAppend} from '../public/core/continuity.mjs';
import {propertyView} from '../public/core/property-lessons.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {playerCalendar,planTimeAdvance} from '../public/core/life-calendar.mjs';
const evidence='Recorded event.',actor='Harry',seller='Owner',currency='GBP';
const life=(life_kind,record_id,extra)=>({id:life_kind+'-'+record_id,type:'world',player_life_version:1,life_kind,record_id,key:'player-life:'+life_kind+':'+record_id,evidence,...extra});
const sc=(id,events=[],world_time='1994-08-01 09:00')=>({id,events,body:evidence,world_time});
const valid=(h,e)=>validateStateAppend(h,e,evidence).ok;
const estate=life('estate','home',{actor:seller,title:'Home',place:'London',estate_kind:'house',status:'owned'});
const offer=life('estate_sale','sale',{actor:seller,buyer:actor,estate_id:'home',amount:100,currency,status:'offered'});
const accepted={...offer,status:'accepted'},settled={...offer,status:'settled',transfer_event_id:'pay',outcome:'Title transferred'};
const cash={id:'cash',type:'money',actor,currency,operation:'reconcile',delta:0,balance:120,evidence};
const pay={id:'pay',type:'money',actor,counterparty:seller,currency,operation:'transfer',delta:-100,evidence};
test('estate title transfers only with one accepted exact payment and preserves previous branches',()=>{
 const h=[sc('start',[estate,offer,cash])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[{...estate,actor}]),false);
 assert.equal(valid(h,[pay,settled]),false);
 h.push(sc('accept',[accepted]));
 assert.equal(valid(h,[settled]),false);
 assert.equal(valid(h,[{...pay,delta:-99},settled]),false);
 assert.equal(valid(h,[pay,settled]),true);
 const next=[...h,sc('sale',[pay,settled])],p=replay(next);
 assert.equal(propertyView(p,actor).estates.total,1);assert.equal(propertyView(p,seller).estates.total,0);
 assert.equal(p.balances.find(x=>x.actor===actor).balance,20);
 assert.equal(propertyView(replay(h),seller).estates.total,1);
 assert.equal(valid(next,[pay,settled]),false);
 assert.equal(valid(next,[life('estate_sale','new',{...offer,id:'new',key:'player-life:estate_sale:new',record_id:'new',actor,buyer:seller,title_revision:'sale',status:'offered'})]),true);
 assert.equal(menuActionIntent({action:'repair_estate',estate_id:'home',detail:'Repair roof'},playerMenuOverview(p,actor)).saved,false);
});
const service=life('venue_service','train',{actor:'Rail',title:'Ticket',place:'Station',category:'transport',amount:0,currency,duration_minutes:60,status:'available'});
const notice=life('transit_notice','train',{actor,provider:'Rail',title:'Train',from:'Station',to:'London',mode:'rail',departs_at:'1994-08-01 10:00',arrives_at:'1994-08-01 11:00',amount:0,currency,status:'scheduled'});
const slot=life('capacity_slot','seat',{actor:'Rail',service_id:'train',resource:'Seat',starts_at:notice.departs_at,ends_at:notice.arrives_at,capacity:1,status:'open'});
const visit=life('service_visit','train',{actor,provider:'Rail',service_id:'train',title:'Ticket',place:'Station',amount:0,currency,status:'accepted'});
const reserve=life('reservation','seat',{actor,slot_id:'seat',visit_id:'train',units:1,status:'reserved'});
const ticket=life('transport_ticket','ticket',{actor,notice_id:'train',reservation_id:'seat',visit_id:'train',title:'Train',from:notice.from,to:notice.to,departs_at:notice.departs_at,arrives_at:notice.arrives_at,status:'reserved'});
test('ticket pins observed terms and requires an actual matching reservation and service',()=>{
 const h=[sc('s',[service,notice,slot,visit,reserve])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[{...ticket,departs_at:'1994-08-01 09:30'}]),false);
 assert.equal(valid(h,[ticket]),true);
 h.push(sc('ticket',[ticket]));
 assert.equal(valid(h,[{...ticket,status:'used'}]),false);
 h.push(sc('reschedule',[{...notice,departs_at:'1994-08-01 12:00',arrives_at:'1994-08-01 13:00'}]));
 assert.equal(propertyView(replay(h),actor).tickets.records[0].departs_at,ticket.departs_at);
 assert.equal(valid(h,[{...visit,status:'completed',outcome:'Arrived'},{...reserve,status:'used'},{...ticket,status:'used'}]),true);
});
const group={id:'school',type:'world',social_record_version:1,social_kind:'group',record_id:'school',key:'social:group:school',name:'School',purpose:'Education',status:'active',evidence};
const institution={id:'institution',type:'world',dynamics_version:1,dynamics_kind:'institution',record_id:'school',key:'dynamics:institution:school',name:'School',group_id:'school',function:'Education',place:'School',status:'operating',description:'School',evidence};
const enrollment=life('enrollment','course',{actor,institution_id:'school',title:'Magic',place:'School',status:'enrolled'});
const lesson=life('lesson','class',{actor,enrollment_id:'course',teacher:'Teacher',title:'Class',place:'School',starts_at:'1994-08-01 10:00',ends_at:'1994-08-01 11:00',status:'scheduled'});
const assignment=life('assignment','homework',{actor,lesson_id:'class',title:'Homework',due_at:'1994-08-02',status:'assigned'});
test('lesson and assignment attendance, deadlines and grades are distinct evidenced states',()=>{
 const h=[sc('school',[group,institution,enrollment,lesson])];
 assert.deepEqual(replay(h).validation_warnings,[]);
 assert.equal(valid(h,[assignment]),false);
 assert.equal(planTimeAdvance(h,replay(h),actor,'1994-08-01 12:00').gate.kind,'lesson');
 assert.ok(playerCalendar(replay(h),actor,'1994-08-01 09:00').entries.some(x=>x.kind==='lesson'));
 assert.equal(valid(h,[{...lesson,status:'attended',outcome:'Attended'},assignment]),true);
 h.push(sc('class',[{...lesson,status:'attended',outcome:'Attended'},assignment]));
 assert.equal(valid(h,[{...assignment,status:'graded',submission:'Work',grade:'A',outcome:'Grade'}]),false);
 h.push(sc('submission',[{...assignment,status:'submitted',submission:'Work'}]));
 assert.equal(valid(h,[{...assignment,status:'graded',submission:'Other',grade:'A',outcome:'Grade'}]),false);
 assert.equal(valid(h,[{...assignment,status:'graded',submission:'Work',grade:'A',outcome:'Grade'}]),true);
 const overview=playerMenuOverview(replay(h),actor);assert.equal(menuSection(overview,'education').data.assignments.records[0].status,'submitted');
});
