import test from 'node:test';
import assert from 'node:assert/strict';
import {documentIndex,documentShapeError} from '../public/core/documents-world.mjs';
import {replay,validateStateAppend,needsStatePreflight,validateScene} from '../public/core/continuity.mjs';
import {playerMenuOverview,menuActionIntent,menuSection} from '../public/core/game-menu.mjs';
import {playerLifeView} from '../public/core/player-life.mjs';
const evidence='Observed the document and recorded the event.';
const e=(k,i,x)=>({id:k+'_'+i,type:'world',document_version:1,document_kind:k,record_id:i,key:'document:'+k+':'+i,evidence,...x});
const scene=(id,events)=>({id,events,body:evidence,world_time:'2000-01-01 12:00'});
const doc=e('document','book',{actor:'Author',title:'Magic resonance',category:'textbook',summary:'Fictional theory',visibility:'public',status:'active'});
const ed=e('edition','first',{actor:'Author',document_id:'book',number:1,title:'Magic resonance',contents:[{id:'one',title:'Resonance'},{id:'two',title:'Limitations'}],status:'published'});
const chapter=e('chapter','ch1',{actor:'Author',edition_id:'first',chapter_id:'one',title:'Resonance',body:'An original fictional textbook.\n\nThe first principle is not universal.',status:'recorded'});
const grant=e('access','grant',{actor:'Author',edition_id:'first',reader:'Hero',basis:'Received a copy',status:'granted'});
const read=e('reading','read1',{actor:'Hero',edition_id:'first',chapter_id:'one',summary:'A theory, not a fact',reaction:'Curious',status:'read'});
const base=[scene('s1',[doc,ed,chapter,grant])];
const ix=h=>documentIndex(h,replay(h));
test('unread chapter text and unrelated readers remain inaccessible; opening is read only',()=>{
 const d=ix(base);assert.deepEqual(d.warnings,[]);
 assert.equal(d.view('Stranger').library.total,0);
 assert.equal(d.view('Hero').library.records[0].read_chapters,0);
 assert.equal(d.read('Hero','first','one').body,null);
 assert.equal(d.read('Hero','first','two').text_available,false);
 assert.throws(()=>d.read('Stranger','first','one'));
 const author=d.read('Author','first','one');assert.equal(author.body,chapter.body);
 assert.equal(d.view('Author').library.records[0].read_chapters,1);
 assert.equal(d.read('Hero','first','one').body,null);
 const h=[...base,scene('s2',[read])],p=replay(h),v=ix(h);
 assert.deepEqual(v.warnings,[]);
 assert.equal(v.read('Hero','first','one').body,chapter.body);
 assert.equal(v.read('Hero','first','one').reaction,'Curious');
 assert.equal(v.view('Hero').library.records[0].progress_percent,50);
 assert.equal((p.knowledge||[]).length,0);
 assert.equal(documentIndex(h,p,{complete:false}).view('Hero').memory_complete,false);
});
test('immutable text, editions, access, note, reading continuity and precise intent validation',()=>{
 assert.ok(needsStatePreflight([chapter]));
 assert.equal(validateStateAppend(base,[{...chapter,body:'Replacement'}],evidence).ok,false);
 assert.equal(validateStateAppend(base,[{...read,actor:'Stranger'}],evidence).ok,false);
 assert.equal(validateStateAppend(base,[{...read,chapter_id:'two'}],evidence).ok,false);
 assert.equal(validateStateAppend(base,[{...grant,actor:'Stranger',record_id:'bad',key:'document:access:bad'}],evidence).ok,false);
 const h=[...base,scene('s2',[read])];
 const note=e('note','n',{actor:'Hero',edition_id:'first',chapter_id:'one',body:'Interesting contradiction.',status:'active'});
 const bookmark=e('bookmark','bm',{actor:'Hero',edition_id:'first',chapter_id:'two',status:'saved'});
 const h2=[...h,scene('s3',[note,bookmark])],v=ix(h2);assert.deepEqual(v.warnings,[]);
 assert.equal(v.read('Hero','first','one').notes[0].body,note.body);
 assert.equal(v.view('Author').notes.total,0);
 assert.equal(v.view('Hero').library.records[0].contents[1].bookmark,true);
 const next={...ed,id:'new',record_id:'second',key:'document:edition:second',number:2,previous_id:'first',status:'draft'};
 const h3=[...h2,scene('s4',[next])];assert.deepEqual(ix(h3).warnings,[]);
 assert.equal(ix(h3).view('Hero').library.total,1);assert.equal(ix(h3).view('Author').library.total,2);
 assert.equal(ix(h3).read('Hero','first','one').body,chapter.body);
 const o=playerMenuOverview(replay(h2),'Hero',null,{scenes:h2});
 assert.ok(menuSection(o,'library').data.books.records.length);
 assert.equal(menuActionIntent({action:'study_document',edition_id:'first',chapter_id:'two',detail:'Study'},o).chapter_id,'two');
 assert.throws(()=>menuActionIntent({action:'study_document',edition_id:'second',chapter_id:'one',detail:'Study'},o));
 assert.throws(()=>menuActionIntent({action:'write_document_note',edition_id:'first',chapter_id:'two',detail:'Note'},o));
 assert.throws(()=>menuActionIntent({action:'publish_document',edition_id:'first',detail:'Publish'},o));
 const revoked=[...h2,scene('s5',[{...grant,status:'revoked'}])];assert.equal(ix(revoked).read('Hero','first','one').body,chapter.body);assert.equal(ix(revoked).view('Hero').library.records[0].access,'previously_read');assert.equal(ix(revoked).view('Hero').library.records[0].contents.length,1);assert.throws(()=>ix(revoked).read('Hero','first','two'));assert.throws(()=>ix(revoked).authoring('Hero','first','one'));
 assert.ok(documentShapeError({...chapter,body:''}));
 assert.equal(validateScene({body:evidence,events:[{...doc,document_version:2}]}).ok,false);
});
test('royalties require separate exact payments; pagination does not disclose unread mail',()=>{
 const money={id:'payment',type:'money',operation:'transfer',actor:'Publisher',counterparty:'Author',currency:'GBP',delta:-10,evidence};
 const royalty=e('royalty','r',{actor:'Publisher',edition_id:'first',recipient:'Author',amount:10,currency:'GBP',transfer_event_id:'payment',status:'paid'});
 assert.equal(validateStateAppend(base,[royalty],evidence).ok,false);
 assert.equal(validateStateAppend(base,[money,{...royalty,amount:11}],evidence).ok,false);
 const h=[...base,scene('s2',[money,royalty])];assert.deepEqual(ix(h).warnings,[]);assert.equal(ix(h).view('Author').royalties.total,1);
 assert.equal(validateStateAppend(base,[money,royalty,{...royalty,id:'r2',record_id:'r2',key:'document:royalty:r2'}],evidence).ok,false);
 const letters=Array.from({length:35},(_,i)=>({player_life_version:1,life_kind:'letter',record_id:'l'+i,sender:'Author',recipient:'Hero',subject:'Letter',message:'Secret '+i,channel:'owl',status:i===34?'read':'delivered'}));
 const v=playerLifeView({worldFacts:letters},'Hero',{offset:30,limit:5});
 assert.equal(v.letters.incoming.total,35);assert.equal(v.letters.incoming.records.length,5);
 assert.equal(v.letters.incoming.records[0].message,null);assert.equal(v.letters.incoming.records[4].message,'Secret 34');
 assert.equal(v.letters.incoming.next_offset,null);
});

test('narrator can retrieve exact stored text before first read without exposing it in menu',()=>{
 const d=ix(base);assert.equal(d.authoring('Hero','first','one').body,chapter.body);
 assert.equal(d.authoring('Hero','first','two').requires_authoring,true);
 assert.equal(d.authoring('Hero','first','two').body,null);
 assert.equal(d.read('Hero','first','one').body,null);
 assert.throws(()=>d.authoring('Stranger','first','one'));
 assert.throws(()=>d.authoring('Hero','first','missing'));
 const o=playerMenuOverview(replay(base),'Hero',null,{scenes:base});
 assert.equal(menuSection(o,'medical_records').data.books.total,0);
 assert.equal(menuSection(o,'catalogues').data.books.total,0);
 const letter=menuActionIntent({action:'send_letter',detail:'Send',letter_recipient:'Friend',letter_subject:'Subject',letter_body:'A'.repeat(3000)},o);
 assert.equal(letter.letter_body.length,3000);
 assert.throws(()=>menuActionIntent({action:'send_letter',detail:'Send',letter_recipient:'Friend',letter_subject:'Subject',letter_body:'A'.repeat(5001)},o));
});
